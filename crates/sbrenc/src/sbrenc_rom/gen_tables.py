def gen_invf_est():
    src = 'libSBRenc/src/invf_est.cpp'
    body = ''
    for name in ('quantStepsSbr', 'quantStepsOrig', 'nrgBorders'):
        body += f'  ARR("{name}", {name}, 4);\n'
    body += '  VAL("hysteresis", hysteresis);\n'
    for i in range(5):
        body += f'  ARR("fir_{i}", fir_{i}, 5);\n'
    body += '  for (int i = 0; i < 5; i++) { long long v[1] = {-1};\n'
    body += '    const FIR_FILTER *c[5] = {&fir_0, &fir_1, &fir_2, &fir_3, &fir_4};\n'
    body += '    for (int j = 0; j < 5; j++) if (fir_table[i] == c[j]) v[0] = j;\n'
    body += '    P("fir_table", 1, v); }\n'
    for name in ('detectorParamsAAC', 'detectorParamsAACSpeech'):
        body += (f'  {{ const DETECTOR_PARAMETERS *d = &{name}; long long v[64]; int k = 0;\n'
                 f'    v[k++] = d->quantStepsSbr == quantStepsSbr; v[k++] = d->quantStepsOrig == quantStepsOrig;\n'
                 f'    v[k++] = d->nrgBorders == nrgBorders; v[k++] = d->numRegionsSbr;\n'
                 f'    v[k++] = d->numRegionsOrig; v[k++] = d->numRegionsNrg;\n'
                 f'    for (int i = 0; i < 5; i++) for (int j = 0; j < 5; j++) v[k++] = d->regionSpace[i][j];\n'
                 f'    for (int i = 0; i < 5; i++) for (int j = 0; j < 5; j++) v[k++] = d->regionSpaceTransient[i][j];\n'
                 f'    for (int i = 0; i < 5; i++) v[k++] = d->EnergyCompFactor[i];\n'
                 f'    P("{name}", k, v); }}\n')
    r = run_rows(src, body)
    items = []
    for name in ('quantStepsSbr', 'quantStepsOrig', 'nrgBorders'):
        items.append(arr(name, r[name][0], 'FixpDbl', 4, hexdbl, rname=rust_name(name)))
    items.append(const('hysteresis', r['hysteresis'][0][0], 'FixpDbl', fmt=hexdbl))
    for i in range(5):
        items.append(arr(f'fir_{i}', r[f'fir_{i}'][0], 'FixpDbl', 5, hexdbl, rname=f'FIR_{i}'))
    idx = [row[0] for row in r['fir_table']]
    assert all(0 <= i < 5 for i in idx)
    items.append('/// `fir_table`\npub static FIR_TABLE: [&[FixpDbl; 5]; 5] = ['
                 + ', '.join(f'&FIR_{i}' for i in idx) + '];\n')
    for name in ('detectorParamsAAC', 'detectorParamsAACSpeech'):
        v = r[name][0]
        assert v[0] == 1 and v[1] == 1 and v[2] == 1
        rs = v[6:31]
        rst = v[31:56]
        ecf = v[56:61]
        grid = lambda g: '[' + ', '.join(str(g[i * 5:(i + 1) * 5]) for i in range(5)) + ']'
        items.append(
            f'/// `{name}`\npub static {rust_name(name)}: DetectorParameters = DetectorParameters {{\n'
            f'    quant_steps_sbr: &QUANT_STEPS_SBR,\n    quant_steps_orig: &QUANT_STEPS_ORIG,\n'
            f'    nrg_borders: &NRG_BORDERS,\n    num_regions_sbr: {v[3]},\n'
            f'    num_regions_orig: {v[4]},\n    num_regions_nrg: {v[5]},\n'
            f'    region_space: {grid(rs)},\n    region_space_transient: {grid(rst)},\n'
            f'    energy_comp_factor: {ecf},\n}};\n')
    uses = 'use super::DetectorParameters;\nuse fdk_aac_rs_fdk::common_fix::FixpDbl;\n'
    write('invf_est', src, uses, items)


