def gen_fram_gen():
    src = 'libSBRenc/src/fram_gen.cpp'
    infos = [f'frameInfo{n}_{t}' for t in ('2048', '2304', '1920', '1152', '512LD')
             for n in (1, 2, 4)]
    body = ''
    for name in infos:
        body += (f'  {{ const SBR_FRAME_INFO *f = &{name}; long long v[17]; int k = 0;\n'
                 f'    v[k++] = f->nEnvelopes; for (int i = 0; i < 6; i++) v[k++] = f->borders[i];\n'
                 f'    for (int i = 0; i < 5; i++) v[k++] = f->freqRes[i]; v[k++] = f->shortEnv;\n'
                 f'    v[k++] = f->nNoiseEnvelopes; for (int i = 0; i < 3; i++) v[k++] = f->bordersNoise[i];\n'
                 f'    P("{name}", 17, v); }}\n')
    body += '  ARR("envelopeTable_8", &envelopeTable_8[0][0], 8 * 5);\n'
    body += '  ARR("envelopeTable_16", &envelopeTable_16[0][0], 16 * 6);\n'
    body += '  ARR("envelopeTable_15", &envelopeTable_15[0][0], 15 * 6);\n'
    body += '  ARR("freqRes_table_8", freqRes_table_8, sizeof(freqRes_table_8) / sizeof(FREQ_RES));\n'
    body += '  ARR("freqRes_table_16", freqRes_table_16, sizeof(freqRes_table_16) / sizeof(FREQ_RES));\n'
    body += '  VAL("minFrameTranDistance", minFrameTranDistance);\n'
    r = single(run_rows(src, body))
    items = []
    for name in infos:
        v = r[name]
        items.append(
            f'/// `{name}`\npub static {rust_name(name)}: SbrFrameInfo = SbrFrameInfo {{\n'
            f'    n_envelopes: {v[0]},\n    borders: {v[1:7]},\n    freq_res: {v[7:12]},\n'
            f'    short_env: {v[12]},\n    n_noise_envelopes: {v[13]},\n'
            f'    borders_noise: {v[14:17]},\n}};\n')
    for name, rows, cols in (('envelopeTable_8', 8, 5), ('envelopeTable_16', 16, 6),
                             ('envelopeTable_15', 15, 6)):
        v = r[name]
        body_r = ''.join(f'    {v[i * cols:(i + 1) * cols]},\n' for i in range(rows))
        items.append(f'/// `{name}`\npub static {rust_name(name)}: [[i32; {cols}]; {rows}] = [\n'
                     f'{body_r}];\n')
    items.append(arr('freqRes_table_8', r['freqRes_table_8'], 'FreqRes', 9))
    items.append(arr('freqRes_table_16', r['freqRes_table_16'], 'FreqRes', 8))
    items.append(const('minFrameTranDistance', r['minFrameTranDistance'][0], 'i32'))
    uses = 'use super::SbrFrameInfo;\nuse crate::sbr_encoder::FreqRes;\n'
    write('fram_gen', src, uses, items)


