def gen_resampler():
    src = 'libSBRenc/src/resampler.cpp'
    sets = ['48', '45', '41', '35', '25']
    body = ''
    for s in sets:
        body += f'  ARR("sos{s}", sos{s}, sizeof(sos{s}) / sizeof(FIXP_SGL));\n'
    body += '  const FIXP_SGL *sos[5] = {sos48, sos45, sos41, sos35, sos25};\n'
    for s in sets:
        body += (f'  {{ const struct FILTER_PARAM *p = &param_set{s}; long long v[6] = {{-1, p->g, '
                 f'p->Wc, p->noCoeffs, p->delay, 0}};\n'
                 f'    for (int j = 0; j < 5; j++) if (p->coeffa == sos[j]) v[0] = j;\n'
                 f'    P("param_set{s}", 5, v); }}\n')
    body += '  { const struct FILTER_PARAM *ps[5] = {&param_set48, &param_set45, &param_set41, &param_set35, &param_set25};\n'
    body += '    long long v[5]; long n = sizeof(filter_paramSet) / sizeof(filter_paramSet[0]);\n'
    body += '    for (long i = 0; i < n; i++) { v[i] = -1; for (int j = 0; j < 5; j++) if (filter_paramSet[i] == ps[j]) v[i] = j; }\n'
    body += '    P("filter_paramSet", n, v); }\n'
    r = single(run_rows(src, body))
    items = []
    for s in sets:
        items.append(arr(f'sos{s}', r[f'sos{s}'], 'FixpSgl', 8, rname=f'SOS{s}'))
    for s in sets:
        v = r[f'param_set{s}']
        assert 0 <= v[0] < 5
        items.append(
            f'/// `param_set{s}`\npub static PARAM_SET{s}: FilterParam = FilterParam {{\n'
            f'    coeffa: &SOS{sets[v[0]]},\n    g: {hexdbl(v[1])},\n    wc: {v[2]},\n'
            f'    no_coeffs: {v[3]},\n    delay: {v[4]},\n}};\n')
