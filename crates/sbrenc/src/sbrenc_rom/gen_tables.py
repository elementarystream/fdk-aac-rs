def gen_sbrenc_rom():
    src = 'libSBRenc/src/sbrenc_rom.cpp'
    text = open(os.path.join(dump_table.CDIR, src)).read()
    huff = re.findall(r'^const (INT|UCHAR) (\w+)\[(\d+)\]\s*=', text, re.M)
    body = ''
    for ctype, name, n in huff:
        body += f'  ARR("{name}", {name}, sizeof({name}) / sizeof({name}[0]));\n'
    fields = ['coreCoder', 'bitrateFrom', 'bitrateTo', 'sampleRate', 'numChannels', 'startFreq',
              'startFreqSpeech', 'stopFreq', 'stopFreqSpeech', 'numNoiseBands',
              'noiseFloorOffset', 'noiseMaxLevel', 'stereoMode', 'freqScale']
    body += '  VAL("sbrTuningTableSize", sbrTuningTableSize);\n'
    body += '  for (int i = 0; i < sbrTuningTableSize; i++) {\n    long long v[14] = {'
    body += ', '.join(f'(long long)sbrTuningTable[i].{f}' for f in fields) + '};\n'
    body += '    P("sbrTuningTable", 14, v);\n  }\n'
    pfields = ['bitrateFrom', 'bitrateTo', 'nStereoBands', 'nEnvelopes', 'iidQuantErrorThreshold']
    body += '  for (int i = 0; i < 4; i++) {\n    long long v[5] = {'
    body += ', '.join(f'(long long)psTuningTable[i].{f}' for f in pfields) + '};\n'
    body += '    P("psTuningTable", 5, v);\n  }\n'
    # The dict keeps the last line of a name; collect the structure rows separately.
    path = os.path.join(dump_table.CDIR, src)
    rows = run_rows(src, body)
    items = []
    for ctype, name, n in huff:
        vals = rows[name][0]
        assert len(vals) == int(n)
        if ctype == 'INT':
            items.append(arr(name, vals, 'i32', 6, hexdbl))
        else:
            items.append(arr(name, vals, 'u8', 12))
    tuning = rows['sbrTuningTable']
    assert len(tuning) == rows['sbrTuningTableSize'][0][0]
    body_r = ''
    for v in tuning:
        (core, bf, bt, sr, nch, sf, sfs, st, sts, nnb, nfo, nml, sm, fs) = v
        body_r += (f'    tt({core}, {bf}, {bt}, {sr}, {nch}, {sf}, {sfs}, {st}, {sts}, {nnb}, '
                   f'{nfo}, {nml}, {sm}, {fs}),\n')
    items.append('/// `sbrTuningTable` (`sbrTuningTable_t` entries, fields in declaration order)\n'
                 f'pub static SBR_TUNING_TABLE: [SbrTuningTable; {len(tuning)}] = [\n{body_r}];\n')
    items.append(const('sbrTuningTableSize', len(tuning), 'i32'))
    ps = rows['psTuningTable']
    body_r = ''.join(f'    PsTuningTable {{ bitrate_from: {a}, bitrate_to: {b}, n_stereo_bands: {c}, '
                     f'n_envelopes: {d}, iid_quant_error_threshold: {hexdbl(e)} }},\n'
                     for a, b, c, d, e in ps)
    items.append('/// `psTuningTable`\n'
                 f'pub static PS_TUNING_TABLE: [PsTuningTable; {len(ps)}] = [\n{body_r}];\n')
    items.append('''#[allow(clippy::too_many_arguments)]
const fn tt(
    core_coder: i32,
    bitrate_from: u32,
    bitrate_to: u32,
    sample_rate: u32,
    num_channels: u8,
    start_freq: u8,
    start_freq_speech: u8,
    stop_freq: u8,
    stop_freq_speech: u8,
    num_noise_bands: u8,
    noise_floor_offset: u8,
    noise_max_level: i8,
    stereo_mode: i32,
    freq_scale: u8,
) -> SbrTuningTable {
    SbrTuningTable {
        core_coder,
        bitrate_from,
        bitrate_to,
        sample_rate,
        num_channels,
        start_freq,
        start_freq_speech,
        stop_freq,
        stop_freq_speech,
        num_noise_bands,
        noise_floor_offset,
        noise_max_level,
        stereo_mode,
        freq_scale,
    }
}
''')
    uses = 'use crate::ps_main::PsTuningTable;\nuse crate::sbr_encoder::SbrTuningTable;\n'
    write('sbrenc_rom', src, uses, items)


def run_rows(src, body, prelude=''):
    """Like run(), but keeps every printed line: name -> list of rows."""
    path = os.path.join(dump_table.CDIR, src)
    prog = f'''#include "{path}"
#include <stdio.h>
{prelude}
static void P(const char *name, long n, const long long *v) {{
  printf("%s %ld", name, n);
  for (long i = 0; i < n; i++) printf(" %lld", v[i]);
  printf("\\n");
}}
#define ARR(name, expr, count) do {{ long long _v[4096]; long _n = (long)(count); \\
  for (long _i = 0; _i < _n; _i++) _v[_i] = (long long)(expr)[_i]; P(name, _n, _v); }} while (0)
#define VAL(name, expr) do {{ long long _v[1] = {{(long long)(expr)}}; P(name, 1, _v); }} while (0)
int main() {{
{body}
  return 0;
}}
'''
    results = {arch: dump_table.dump(prog, arch) for arch in dump_table.archs(None)}
    first = next(iter(results.values()))
    for arch, out in results.items():
        if out != first:
            sys.exit(f'error: {src}: tables differ between architectures')
    out = {}
    toks = first
    i = 0
    while i < len(toks):
        name = toks[i]
        n = int(toks[i + 1])
        out.setdefault(name, []).append([int(t) for t in toks[i + 2:i + 2 + n]])
        i += 2 + n
    return out


def single(rows):
    return {k: v[0] for k, v in rows.items()}


