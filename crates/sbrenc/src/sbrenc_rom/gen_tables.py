#!/usr/bin/env python3
"""Generate the constant tables of libSBRenc as Rust source (`crates/sbrenc/src/*/tables.rs`).

Nothing is retyped. For every C++ source file of libSBRenc that defines tables, a small program
#includes the source file (so that file-static tables are visible), and prints every value with
the exact compiler semantics of the reference build. The program is compiled and run for arm64
and x86_64 (scripts/dump_table.py's compiler setup); the generator fails if they differ.

* Arrays at file scope are printed by name.
* Arrays that are local variables of a function (the `v_offset` and `v_stop_freq_*` tables of
  sbrenc_freq_sca.cpp, the `v_tuning*` tables of env_est.cpp) cannot be named from outside the
  function: their initializers are cut out of the C++ source text with a regular expression and
  compiled as file-scope arrays of the same type in the dump program.
* Structure tables are printed field by field. Pointer fields to other tables are checked in the
  dump program (it prints the index of the table they point to) and written as references to
  the generated Rust tables.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/sbrenc/src/sbrenc_rom/gen_tables.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.abspath(os.path.join(HERE, '..'))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from {src}.
//
// GENERATED by `python3 crates/sbrenc/src/sbrenc_rom/gen_tables.py`; do not edit. Every value is
// printed by a program that #includes {src}, compiled for arm64 and x86_64 (the generator
// checks that both give the same values).

//! The constant tables of `{base}`.
'''


def local_array(src, ctype, name, occurrence=0):
    """The definition `ctype name[...] = {...};` of a function-local array, as file-scope C++."""
    text = open(os.path.join(dump_table.CDIR, src)).read()
    pat = re.compile(r'(?:static\s+)?(?:const\s+)?' + re.escape(ctype) + r'\s+' + re.escape(name)
                     + r'\s*\[[^\]]*\]\s*=\s*(\{[^;]*\});', re.S)
    m = list(pat.finditer(text))
    if len(m) <= occurrence:
        sys.exit(f'error: {name} not found in {src}')
    return m[occurrence].group(1)


def lines(items, per_line):
    return ''.join('    ' + ', '.join(items[i:i + per_line]) + ',\n'
                   for i in range(0, len(items), per_line))


def rust_name(c):
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'([A-Za-z])(\d)', r'\1_\2', s)
    return s.upper()


def hexdbl(v):
    return f'0x{v & 0xffffffff:08X}u32 as i32' if v < 0 else f'0x{v:08X}'


def arr(cname, vals, rtype, per_line=12, fmt=str, rname=None, vis='pub', comment=None):
    rname = rname or rust_name(cname)
    doc = comment or f'`{cname}`'
    return (f'/// {doc}\n{vis} static {rname}: [{rtype}; {len(vals)}] = [\n'
            f'{lines([fmt(v) for v in vals], per_line)}];\n')


def const(cname, val, rtype, rname=None, fmt=str):
    rname = rname or rust_name(cname)
    return f'/// `{cname}`\npub const {rname}: {rtype} = {fmt(val)};\n'


def write(module, src, uses, items):
    out = HEADER.format(src=src, base=os.path.basename(src)) + '\n' + uses + '\n'
    out += '\n'.join(items)
    path = os.path.join(SRC_DIR, module, 'tables.rs')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write(out)
    print(f'{path}: {len(items)} items')


