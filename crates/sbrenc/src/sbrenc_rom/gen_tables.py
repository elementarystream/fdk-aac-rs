def gen_freq_sca():
    src = 'libSBRenc/src/sbrenc_freq_sca.cpp'
    text = open(os.path.join(dump_table.CDIR, src)).read()
    # getStartFreq(): one local `v_offset` per case of the second switch, in source order.
    offs = re.findall(r'INT v_offset\[\]\s*=\s*(\{[^;]*\});', text)
    stops = re.findall(r'INT (v_stop_freq_\d+)\[14\]\s*=\s*(\{[^;]*\});', text)
    prelude = ''.join(f'static const INT dump_v_offset_{i}[] = {o};\n' for i, o in enumerate(offs))
    prelude += ''.join(f'static const INT dump_{n}[14] = {o};\n' for n, o in stops)
    body = ''.join(f'  ARR("v_offset_{i}", dump_v_offset_{i}, sizeof(dump_v_offset_{i}) / sizeof(INT));\n'
                   for i in range(len(offs)))
    body += ''.join(f'  ARR("{n}", dump_{n}, 14);\n' for n, _ in stops)
    r = single(run_rows(src, body, prelude))
    # The case labels of the second switch of getStartFreq() in source order.
    m = re.search(r'static INT getStartFreq\([^)]*\)\s*\{.*?\n\}', text, re.S)
    sw = m.group(0).split('switch (fsCore)')[2]
    groups = re.findall(r'((?:\s*case \d+:)+|\s*default:)\s*\{\s*INT v_offset', sw)
    assert len(groups) == len(offs), (len(groups), len(offs))
    items = []
    for i, g in enumerate(groups):
        labels = re.findall(r'case (\d+):', g) or ['default']
        items.append(arr(f'v_offset_{i}', r[f'v_offset_{i}'], 'i32', 16, rname=f'V_OFFSET_{i}',
                         comment=f'`v_offset` of `getStartFreq()` for `fsCore` = {", ".join(labels)}'))
    for n, _ in stops:
        items.append(arr(n, r[n], 'i32', 14, comment=f'`{n}` (a local of `getStopFreq()`)'))
    write('sbrenc_freq_sca', src, '', items)


