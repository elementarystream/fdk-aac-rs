def gen_ps_bitenc():
    src = 'libSBRenc/src/ps_bitenc.cpp'
    text = open(os.path.join(dump_table.CDIR, src)).read()
    tabs = re.findall(r'^static const UINT (\w+)\[\]\s*=', text, re.M)
    consts = re.findall(r'^static const INT (\w+)\s*=', text, re.M)
    body = ''.join(f'  ARR("{t}", {t}, sizeof({t}) / sizeof(UINT));\n' for t in tabs)
    body += ''.join(f'  VAL("{c}", {c});\n' for c in consts)
    r = single(run_rows(src, body))
    items = [const(c, r[c][0], 'i32') for c in consts]
    for t in tabs:
        if t.endswith('_Code'):
            items.append(arr(t, r[t], 'u32', 6, lambda v: f'0x{v:08X}'))
        else:
            items.append(arr(t, r[t], 'u32', 16))
    write('ps_bitenc', src, '', items)


