#!/usr/bin/env python3
"""Generate crates/aacenc/src/aacenc_tns/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the tables are the file-static
tables of libAACenc/src/aacenc_tns.cpp, dumped as memory (struct tables as their scalar fields or
bytes) and decoded here.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/aacenc_tns/gen_tables.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
SRC = 'libAACenc/src/aacenc_tns.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libAACenc/src/aacenc_tns.cpp.
//
// GENERATED by `python3 crates/aacenc/src/aacenc_tns/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! The file-static tables of `aacenc_tns.cpp`.

use super::{TnsInfoTab, TnsMaxTabEntry, TnsParameterTabulated};
use fdk_aac_rs_fdk::common_fix::FixpDbl;
'''


def dump(symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def cmd(symbol, elemtype):
    return f'`scripts/dump_table.py {SRC} {symbol} {elemtype}`'


def hx(v):
    return f'0x{v & 0xFFFFFFFF:08X}' + ('u32 as i32' if v < 0 else '')


def param_tab(w, indent):
    """TNS_PARAMETER_TABULATED from its 15 INT words."""
    assert len(w) == 15
    p = ' ' * indent
    f = lambda a: f'[{a[0]}, {a[1]}]'
    return (f'TnsParameterTabulated {{\n'
            f'{p}    filter_enabled: {f(w[0:2])},\n'
            f'{p}    thresh_on: {f(w[2:4])},\n'
            f'{p}    filter_start_freq: {f(w[4:6])},\n'
            f'{p}    tns_limit_order: {f(w[6:8])},\n'
            f'{p}    tns_filter_direction: {f(w[8:10])},\n'
            f'{p}    acf_split: {f(w[10:12])},\n'
            f'{p}    tns_time_resolution: [{hx(w[12])}, {hx(w[13])}],\n'
            f'{p}    seperate_filters_allowed: {w[14]},\n'
            f'{p}}}')


def main():
    out = HEADER
    for name, rname in (('acfWindowLong', 'ACF_WINDOW_LONG'), ('acfWindowShort', 'ACF_WINDOW_SHORT')):
        v = dump(name, 'LONG')
        rows = ''.join('    ' + ', '.join(hx(x) for x in v[i:i + 4]) + ',\n'
                       for i in range(0, len(v), 4))
        out += (f'\n/// `{name}`\n///\n/// Generated with {cmd(name, "LONG")}.\n'
                f'pub static {rname}: [FixpDbl; {len(v)}] = [\n{rows}];\n')

    # TNS_INFO_TAB: INT bitRateFrom[2], bitRateTo[2], TNS_PARAMETER_TABULATED paramTab[2]
    v = dump('tnsInfoTab', 'INT')
    per = 4 + 2 * 15
    assert len(v) % per == 0
    out += (f'\n/// `tnsInfoTab`\n///\n/// Generated with {cmd("tnsInfoTab", "INT")}.\n'
            f'pub static TNS_INFO_TAB: [TnsInfoTab; {len(v) // per}] = [\n')
    for e in range(len(v) // per):
        w = v[e * per:(e + 1) * per]
        out += (f'    TnsInfoTab {{\n'
                f'        bit_rate_from: [{w[0]}, {w[1]}],\n'
                f'        bit_rate_to: [{w[2]}, {w[3]}],\n'
                f'        param_tab: [\n'
                f'            {param_tab(w[4:19], 12)},\n'
                f'            {param_tab(w[19:34], 12)},\n'
                f'        ],\n'
                f'    }},\n')
    out += '];\n'

    # TNS_MAX_TAB_ENTRY: INT samplingRate, SCHAR maxBands[2], 2 bytes of padding
    for n in ('1024', '120', '128', '240', '256', '480', '512'):
        name = f'tnsMaxBandsTab{n}'
        b = dump(name, 'SCHAR')
        assert len(b) % 8 == 0
        ents = []
        for e in range(len(b) // 8):
            x = bytes(c & 0xFF for c in b[e * 8:e * 8 + 8])
            rate = int.from_bytes(x[0:4], 'little', signed=True)
            mb = [c - 256 if c > 127 else c for c in x[4:6]]
            pad = [c - 256 if c > 127 else c for c in x[6:8]]
            ents.append(f'    TnsMaxTabEntry {{ sampling_rate: {rate}, max_bands: [{mb[0]}, {mb[1]}], '
                        f'_pad: [{pad[0]}, {pad[1]}] }},\n')
        out += (f'\n/// `{name}`\n///\n/// Generated with {cmd(name, "SCHAR")}\n/// (decoded as '
                f'`INT samplingRate`, `SCHAR maxBands[2]` and two padding bytes).\n'
                f'pub static TNS_MAX_BANDS_TAB_{n}: [TnsMaxTabEntry; {len(ents)}] = [\n'
                + ''.join(ents) + '];\n')

    path = os.path.join(HERE, 'tables.rs')
    open(path, 'w').write(out)
    # format as `cargo fmt` does (rustfmt.toml of the repository)
    subprocess.run(['rustfmt', '--edition', '2021', path], check=True, cwd=REPO)


if __name__ == '__main__':
    main()
