#!/usr/bin/env python3
"""Generate crates/aacenc/src/aac_enc_rom/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the list of tables, their
element types and their dimensions are taken from the definitions in libAACenc/src/aacEnc_rom.cpp.
SFB_PARAM_LONG / SFB_PARAM_SHORT structs are dumped as UCHAR (sfbCnt followed by sfbWidth[]).

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/aac_enc_rom/gen_tables.py [-j JOBS]
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402  (for the location of the C++ sources)

SRC = 'libAACenc/src/aacEnc_rom.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libAACenc/src/aacEnc_rom.cpp.
//
// GENERATED by `python3 crates/aacenc/src/aac_enc_rom/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.
'''

# C element type -> (dump type, Rust element type)
TYPES = {
    'ULONG': ('ULONG', 'u32'),
    'UCHAR': ('UCHAR', 'u8'),
    'USHORT': ('USHORT', 'u16'),
    'SHORT': ('SHORT', 'i16'),
    'FIXP_QTD': ('SHORT', 'FixpQtd'),
    'FIXP_LPC': ('SHORT', 'FixpLpc'),
    'FIXP_WTB': ('SHORT', 'FixpWtb'),
    'FIXP_DBL': ('LONG', 'FixpDbl'),
}

DEFINES = {'MANT_SIZE': 512}


def rust_name(c):
    """Mechanical SCREAMING_SNAKE_CASE name of a C table."""
    s = c.replace('FDKaacEnc', 'FdkAacEnc')
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', s)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'([A-Za-z])(\d)', r'\1_\2', s)
    s = re.sub(r'(\d)([A-Za-z])', r'\1_\2', s)
    s = re.sub(r'_+', '_', s)
    return s.upper().strip('_')


def dump(symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def fmt(v, rtype):
    if rtype in ('u32', 'FixpDbl'):
        return f'0x{v & 0xFFFFFFFF:08X}' + ('u32 as i32' if rtype == 'FixpDbl' and v < 0 else '')
    if rtype == 'u16':
        return f'0x{v:04X}'
    return str(v)


def nest(vals, dims, rtype, indent):
    """Nested array literal of vals with the given dimensions."""
    if len(dims) == 1:
        per = 8 if rtype in ('u32', 'FixpDbl', 'u16') else 12
        items = [fmt(v, rtype) for v in vals]
        pad = '    ' * (indent + 1)
        rows = [pad + ', '.join(items[i:i + per]) + ',' for i in range(0, len(items), per)]
        return '[\n' + '\n'.join(rows) + '\n' + '    ' * indent + ']'
    step = len(vals) // dims[0]
    parts = [nest(vals[i * step:(i + 1) * step], dims[1:], rtype, indent + 1)
             for i in range(dims[0])]
    pad = '    ' * (indent + 1)
    return '[\n' + ''.join(pad + p + ',\n' for p in parts) + '    ' * indent + ']'


def rust_type(rtype, dims):
    t = rtype
    for d in reversed(dims):
        t = f'[{t}; {d}]'
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()
    src = open(os.path.join(dump_table.CDIR, SRC)).read()

    arrays = re.findall(r'^const (\w+) (\w+)((?:\[[^\]]*\])+)\s*=', src, re.M)
    structs = re.findall(r'^const (SFB_PARAM_LONG|SFB_PARAM_SHORT) (\w+)\s*=', src, re.M)

    jobs = [(name, TYPES[ctype][0]) for ctype, name, _ in arrays]
    jobs += [(name, 'UCHAR') for _, name in structs]
    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        vals = list(ex.map(lambda j: dump(*j), jobs))

    out = HEADER + '''
//! The constant tables of `aacEnc_rom.cpp`.

use crate::psy_configuration::{SfbParamLong, SfbParamShort};
use fdk_aac_rs_fdk::archdef::FixpWtb;
use fdk_aac_rs_fdk::common_fix::FixpDbl;
use fdk_aac_rs_fdk::lpc::FixpLpc;

/// `FIXP_QTD` (`FIXP_SGL`)
pub type FixpQtd = i16;
'''
    i = 0
    for ctype, name, dimtext in arrays:
        dims = []
        for d in re.findall(r'\[([^\]]*)\]', dimtext):
            d = d.strip()
            dims.append(int(DEFINES.get(d, d)) if d else None)
        v = vals[i]
        i += 1
        if dims[-1] is None or None in dims:
            assert dims == [None]
            dims = [len(v)]
        n = 1
        for d in dims:
            n *= d
        assert n == len(v), (name, dims, len(v))
        dtype, rtype = TYPES[ctype]
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} {dtype}`.\n'
                f'pub static {rust_name(name)}: {rust_type(rtype, dims)} = {nest(v, dims, rtype, 0)};\n')
    for ctype, name in structs:
        v = vals[i]
        i += 1
        width = 51 if ctype == 'SFB_PARAM_LONG' else 15
        rtype = 'SfbParamLong' if ctype == 'SFB_PARAM_LONG' else 'SfbParamShort'
        assert len(v) == 1 + width, (name, len(v))
        w = ', '.join(str(x) for x in v[1:])
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} UCHAR`.\n'
                f'pub static {rust_name(name)}: {rtype} = {rtype} {{\n'
                f'    sfb_cnt: {v[0]},\n    sfb_width: [{w}],\n}};\n')
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)
    print(f'{len(arrays)} arrays, {len(structs)} SFB parameter structs')


if __name__ == '__main__':
    main()
