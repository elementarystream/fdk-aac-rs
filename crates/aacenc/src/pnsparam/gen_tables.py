#!/usr/bin/env python3
"""Generate crates/aacenc/src/pnsparam/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the tables are the file-static
tables of libAACenc/src/pnsparam.cpp, dumped as memory and decoded here.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/pnsparam/gen_tables.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
SRC = 'libAACenc/src/pnsparam.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libAACenc/src/pnsparam.cpp.
//
// GENERATED by `python3 crates/aacenc/src/pnsparam/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! The file-static tables of `pnsparam.cpp`.

use super::{AutoPnsTab, PnsInfoTab};
'''


def dump(symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def cmd(symbol, elemtype):
    return f'`scripts/dump_table.py {SRC} {symbol} {elemtype}`'


def main():
    out = HEADER
    # AUTO_PNS_TAB: ULONG brFrom, ULONG brTo, UCHAR S16000 .. S48000, 2 bytes of padding
    for name, rname in (('levelTable_mono', 'LEVEL_TABLE_MONO'),
                        ('levelTable_stereo', 'LEVEL_TABLE_STEREO'),
                        ('levelTable_lowComplexity', 'LEVEL_TABLE_LOW_COMPLEXITY')):
        b = dump(name, 'UCHAR')
        assert len(b) % 16 == 0
        ents = []
        for e in range(len(b) // 16):
            x = bytes(b[e * 16:e * 16 + 16])
            fr = int.from_bytes(x[0:4], 'little')
            to = int.from_bytes(x[4:8], 'little')
            s = list(x[8:14])
            ents.append(f'    AutoPnsTab {{\n        br_from: {fr},\n        br_to: {to},\n'
                        f'        s16000: {s[0]},\n        s22050: {s[1]},\n'
                        f'        s24000: {s[2]},\n        s32000: {s[3]},\n'
                        f'        s44100: {s[4]},\n        s48000: {s[5]},\n'
                        f'        _pad: [{x[14]}, {x[15]}],\n    }},\n')
        out += (f'\n/// `{name}`\n///\n/// Generated with {cmd(name, "UCHAR")}\n'
                f'/// (decoded as `ULONG brFrom`, `ULONG brTo`, `UCHAR S16000` .. `S48000` and two '
                f'padding bytes).\n'
                f'pub static {rname}: [AutoPnsTab; {len(ents)}] = [\n' + ''.join(ents) + '];\n')

    # PNS_INFO_TAB: eight 16-bit fields
    for name, rname in (('pnsInfoTab', 'PNS_INFO_TAB'),
                        ('pnsInfoTab_lowComplexity', 'PNS_INFO_TAB_LOW_COMPLEXITY')):
        v = dump(name, 'SHORT')
        assert len(v) % 8 == 0
        ents = []
        for e in range(len(v) // 8):
            w = v[e * 8:e * 8 + 8]
            ents.append(f'    PnsInfoTab {{\n        start_freq: {w[0]},\n        ref_power: {w[1]},\n'
                        f'        ref_tonality: {w[2]},\n        tns_gain_threshold: {w[3]},\n'
                        f'        tns_pns_gain_threshold: {w[4]},\n        gap_fill_thr: {w[5]},\n'
                        f'        min_sfb_width: {w[6]},\n'
                        f'        detection_algorithm_flags: {w[7] & 0xFFFF},\n    }},\n')
        out += (f'\n/// `{name}`\n///\n/// Generated with {cmd(name, "SHORT")}\n'
                f'/// (decoded as the eight 16-bit fields of `PNS_INFO_TAB`).\n'
                f'pub static {rname}: [PnsInfoTab; {len(ents)}] = [\n' + ''.join(ents) + '];\n')

    path = os.path.join(HERE, 'tables.rs')
    open(path, 'w').write(out)
    # format as `cargo fmt` does (rustfmt.toml of the repository)
    subprocess.run(['rustfmt', '--edition', '2021', path], check=True, cwd=REPO)


if __name__ == '__main__':
    main()
