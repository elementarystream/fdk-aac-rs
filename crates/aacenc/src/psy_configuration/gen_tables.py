#!/usr/bin/env python3
"""Generate crates/aacenc/src/psy_configuration/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the tables are the file-static
tables of libAACenc/src/psy_configuration.cpp. The SFB_INFO_TAB tables hold pointers to
SFB_PARAM_LONG / SFB_PARAM_SHORT tables; a small prelude turns every pointer into the index of the
table it points to (in CANDIDATES), which is dumped together with the sample rate.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/psy_configuration/gen_tables.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
SRC = 'libAACenc/src/psy_configuration.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libAACenc/src/psy_configuration.cpp.
//
// GENERATED by `python3 crates/aacenc/src/psy_configuration/gen_tables.py`; do not edit. Every
// table is dumped with scripts/dump_table.py (the command is given at each table), which checks that
// the arm64 and x86_64 builds give the same values.

//! The file-static tables of `psy_configuration.cpp`.

use super::{SfbInfoTab, SfbParamLong};
use crate::aac_enc_rom::*;
'''

RATES = [8000, 11025, 12000, 16000, 22050, 24000, 32000, 44100, 48000, 64000, 88200, 96000]
LOCAL = ['p_22050_long_512', 'p_32000_long_512', 'p_44100_long_512',
         'p_22050_long_480', 'p_32000_long_480', 'p_44100_long_480']
CANDIDATES = ([f'p_FDKaacEnc_{r}_long_1024' for r in RATES]
              + [f'p_FDKaacEnc_{r}_short_128' for r in RATES] + LOCAL)
# The p_FDKaacEnc_* tables are defined in aacEnc_rom.cpp, which is compiled into the same program.
PRELUDE_HEAD = '#include "aacEnc_rom.cpp"\n'


def rust_name(c):
    """Mechanical SCREAMING_SNAKE_CASE name of a C table (as aac_enc_rom/gen_tables.py)."""
    s = c.replace('FDKaacEnc', 'FdkAacEnc')
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', s)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'([A-Za-z])(\d)', r'\1_\2', s)
    s = re.sub(r'(\d)([A-Za-z])', r'\1_\2', s)
    s = re.sub(r'_+', '_', s)
    return s.upper().strip('_')


def dump(symbol, elemtype, prelude='', count=None):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype,
           '--prelude', PRELUDE_HEAD + prelude]
    if count:
        cmd += ['--count', count]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def info_prelude(table):
    cands = ', '.join(f'(const void *)&{c}' for c in CANDIDATES)
    return f'''static const void *const gen_cands[] = {{{cands}}};
static INT gen_idx(const void *p) {{
  if (p == NULL) return -1;
  for (INT k = 0; k < (INT)(sizeof(gen_cands) / sizeof(gen_cands[0])); k++)
    if (gen_cands[k] == p) return k;
  return -2;
}}
static INT gen_out[3 * (sizeof({table}) / sizeof({table}[0]))];
static int gen_fill() {{
  for (INT i = 0; i < (INT)(sizeof({table}) / sizeof({table}[0])); i++) {{
    gen_out[3 * i] = {table}[i].sampleRate;
    gen_out[3 * i + 1] = gen_idx({table}[i].paramLong);
    gen_out[3 * i + 2] = gen_idx({table}[i].paramShort);
  }}
  return 0;
}}
static int gen_dummy = gen_fill();
'''


def main():
    out = HEADER
    for name in LOCAL:
        v = dump(name, 'UCHAR')
        assert len(v) == 52, (name, len(v))
        w = ', '.join(str(x) for x in v[1:])
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} UCHAR`.\n'
                f'pub static {rust_name(name)}: SfbParamLong = SfbParamLong {{\n'
                f'    sfb_cnt: {v[0]},\n    sfb_width: [{w}],\n}};\n')

    for name, rname in (('sfbInfoTab', 'SFB_INFO_TAB'), ('sfbInfoTabLD512', 'SFB_INFO_TAB_LD_512'),
                        ('sfbInfoTabLD480', 'SFB_INFO_TAB_LD_480')):
        v = dump('gen_out', 'INT', info_prelude(name))
        assert len(v) % 3 == 0
        ents = []
        for e in range(len(v) // 3):
            rate, lo, sh = v[3 * e:3 * e + 3]
            assert lo >= 0 and sh >= -1, (name, e, lo, sh)
            short = 'None' if sh < 0 else f'Some(&{rust_name(CANDIDATES[sh])})'
            ents.append(f'    SfbInfoTab {{\n        sample_rate: {rate},\n'
                        f'        param_long: &{rust_name(CANDIDATES[lo])},\n'
                        f'        param_short: {short},\n    }},\n')
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} gen_out INT '
                f'--prelude ...`\n/// (the sample rates and the tables the pointers refer to; see '
                f'gen_tables.py).\n'
                f'pub static {rname}: [SfbInfoTab; {len(ents)}] = [\n' + ''.join(ents) + '];\n')

    path = os.path.join(HERE, 'tables.rs')
    open(path, 'w').write(out)
    # format as `cargo fmt` does (rustfmt.toml of the repository)
    subprocess.run(['rustfmt', '--edition', '2021', path], check=True, cwd=REPO)


if __name__ == '__main__':
    main()
