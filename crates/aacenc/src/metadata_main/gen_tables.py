#!/usr/bin/env python3
"""Generate the tables of the encoder glue from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the tables are the file-static
tables of libAACenc/src/{aacenc,metadata_main,mps_main,aacenc_lib}.cpp, dumped as memory and
decoded here. Writes:

  crates/aacenc/src/aacenc/tables.rs         configTabVBR
  crates/aacenc/src/metadata_main/tables.rs  dmxTable, dmxLfeTable, surmix2matrix_mixdown_idx,
                                             defaultMetaDataSetup
  crates/aacenc/src/mps_main/tables.rs       mpsConfigTab
  crates/aacenc/src/aacenc_lib/tables.rs     eldSbrAutoConfigTab

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/metadata_main/gen_tables.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRCDIR = os.path.abspath(os.path.join(HERE, '..'))
REPO = os.path.abspath(os.path.join(SRCDIR, '..', '..', '..'))


def header(src, desc, uses):
    return f'''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from {src}.
//
// GENERATED by `python3 crates/aacenc/src/metadata_main/gen_tables.py`; do not edit. Every table
// is dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! {desc}
{uses}'''


def dump(src, symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), src, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def cmd(src, symbol, elemtype):
    return f'`scripts/dump_table.py {src} {symbol} {elemtype}`'


def le(b, o, n, signed=False):
    return int.from_bytes(bytes(b[o:o + n]), 'little', signed=signed)


def write(path, text):
    with open(path, 'w') as f:
        f.write(text)
    # Format as `cargo fmt` does (the repository's rustfmt.toml).
    subprocess.run(['rustfmt', '--edition', '2021', '--config-path',
                    os.path.join(REPO, 'rustfmt.toml'), path], check=True)
    print('wrote', os.path.relpath(path, REPO))


def gen_aacenc():
    src = 'libAACenc/src/aacenc.cpp'
    v = dump(src, 'configTabVBR', 'INT')
    assert len(v) % 3 == 0
    ents = ''.join(
        f'    ConfigTabEntryVbr {{ bitrate_mode: {v[i]}, chan_bitrate: [{v[i + 1]}, {v[i + 2]}] }},\n'
        for i in range(0, len(v), 3))
    out = header(src, 'The file-static tables of `aacenc.cpp`.',
                 '\nuse super::ConfigTabEntryVbr;\n')
    out += (f'\n/// `configTabVBR`\n///\n/// Generated with {cmd(src, "configTabVBR", "INT")}\n'
            f'/// (decoded as `AACENC_BITRATE_MODE bitrateMode`, `int chanBitrate[2]`).\n'
            f'pub(super) static CONFIG_TAB_VBR: [ConfigTabEntryVbr; {len(v) // 3}] = [\n'
            + ents + '];\n')
    write(os.path.join(SRCDIR, 'aacenc', 'tables.rs'), out)


def gen_metadata_main():
    src = 'libAACenc/src/metadata_main.cpp'
    out = header(src, 'The file-static tables of `metadata_main.cpp`.',
                 '\nuse crate::aacenc_lib::{AacencExtMetaData, AacencMetaData};\n'
                 'use fdk_aac_rs_fdk::common_fix::FixpDbl;\n')
    for name, rname in (('dmxTable', 'DMX_TABLE'), ('dmxLfeTable', 'DMX_LFE_TABLE')):
        v = dump(src, name, 'FIXP_DBL')
        body = ''.join(f'    {x},\n' for x in v)
        out += (f'\n/// `{name}`\n///\n/// Generated with {cmd(src, name, "FIXP_DBL")}.\n'
                f'pub(super) static {rname}: [FixpDbl; {len(v)}] = [\n' + body + '];\n')
    v = dump(src, 'surmix2matrix_mixdown_idx', 'UCHAR')
    out += (f'\n/// `surmix2matrix_mixdown_idx`\n///\n/// Generated with '
            f'{cmd(src, "surmix2matrix_mixdown_idx", "UCHAR")}.\n'
            f'pub(super) static SURMIX2MATRIX_MIXDOWN_IDX: [u8; {len(v)}] = '
            f'[{", ".join(map(str, v))}];\n')
    b = dump(src, 'defaultMetaDataSetup', 'UCHAR')
    assert len(b) == 52, len(b)
    # AACENC_MetaData: INT drc_profile, comp_profile, drc_TargetRefLevel, comp_TargetRefLevel,
    # prog_ref_level_present, prog_ref_level; UCHAR PCE_mixdown_idx_present,
    # ETSI_DmxLvl_present; SCHAR centerMixLevel, surroundMixLevel; UCHAR dolbySurroundMode,
    # drcPresentationMode; 2 padding bytes; ExtMetaData at 32: UCHAR extAncDataEnable,
    # extDownmixLevelEnable, extDownmixLevel_A, extDownmixLevel_B, dmxGainEnable, 3 padding
    # bytes, INT dmxGain5, dmxGain2, UCHAR lfeDmxEnable, lfeDmxLevel, 2 padding bytes.
    assert b[30] == b[31] == b[37] == b[38] == b[39] == b[50] == b[51] == 0
    e = 32
    out += (f'\n/// `defaultMetaDataSetup`\n///\n/// Generated with '
            f'{cmd(src, "defaultMetaDataSetup", "UCHAR")} (decoded in the layout of\n'
            f'/// `AACENC_MetaData`, see [`AacencMetaData`]).\n'
            f'pub(super) static DEFAULT_META_DATA_SETUP: AacencMetaData = AacencMetaData {{\n'
            f'    drc_profile: {le(b, 0, 4, True)},\n'
            f'    comp_profile: {le(b, 4, 4, True)},\n'
            f'    drc_target_ref_level: {le(b, 8, 4, True)},\n'
            f'    comp_target_ref_level: {le(b, 12, 4, True)},\n'
            f'    prog_ref_level_present: {le(b, 16, 4, True)},\n'
            f'    prog_ref_level: {le(b, 20, 4, True)},\n'
            f'    pce_mixdown_idx_present: {b[24]},\n'
            f'    etsi_dmx_lvl_present: {b[25]},\n'
            f'    center_mix_level: {le(b, 26, 1, True)},\n'
            f'    surround_mix_level: {le(b, 27, 1, True)},\n'
            f'    dolby_surround_mode: {b[28]},\n'
            f'    drc_presentation_mode: {b[29]},\n'
            f'    _pad0: [0; 2],\n'
            f'    ext_meta_data: AacencExtMetaData {{\n'
            f'        ext_anc_data_enable: {b[e]},\n'
            f'        ext_downmix_level_enable: {b[e + 1]},\n'
            f'        ext_downmix_level_a: {b[e + 2]},\n'
            f'        ext_downmix_level_b: {b[e + 3]},\n'
            f'        dmx_gain_enable: {b[e + 4]},\n'
            f'        _pad0: [0; 3],\n'
            f'        dmx_gain5: {le(b, e + 8, 4, True)},\n'
            f'        dmx_gain2: {le(b, e + 12, 4, True)},\n'
            f'        lfe_dmx_enable: {b[e + 16]},\n'
            f'        lfe_dmx_level: {b[e + 17]},\n'
            f'        _pad1: [0; 2],\n'
            f'    }},\n'
            f'}};\n')
    write(os.path.join(SRCDIR, 'metadata_main', 'tables.rs'), out)


def gen_mps_main():
    src = 'libAACenc/src/mps_main.cpp'
    v = dump(src, 'mpsConfigTab', 'UINT')
    assert len(v) % 6 == 0
    ents = ''.join(
        f'    MpsConfigTab {{\n        audio_object_type: {v[i]},\n        channel_mode: {v[i + 1]},\n'
        f'        sbr_ratio: {v[i + 2]},\n        sampling_rate: {v[i + 3]},\n'
        f'        bitrate_min: {v[i + 4]},\n        bitrate_max: {v[i + 5]},\n    }},\n'
        for i in range(0, len(v), 6))
    out = header(src, 'The file-static tables of `mps_main.cpp`.', '\nuse super::MpsConfigTab;\n')
    out += (f'\n/// `mpsConfigTab`\n///\n/// Generated with {cmd(src, "mpsConfigTab", "UINT")}\n'
            f'/// (decoded as `AUDIO_OBJECT_TYPE`, `CHANNEL_MODE` and four `ULONG`s).\n'
            f'pub(super) static MPS_CONFIG_TAB: [MpsConfigTab; {len(v) // 6}] = [\n'
            + ents + '];\n')
    write(os.path.join(SRCDIR, 'mps_main', 'tables.rs'), out)


def gen_aacenc_lib():
    src = 'libAACenc/src/aacenc_lib.cpp'
    b = dump(src, 'eldSbrAutoConfigTab', 'UCHAR')
    assert len(b) % 20 == 0
    ents = ''
    for o in range(0, len(b), 20):
        # ULONG nChannels, samplingRate, bitrateRange; UCHAR sbrMode; 3 padding bytes;
        # CHANNEL_MODE chMode
        ents += (f'    EldSbrConfigurator {{\n        n_channels: {le(b, o, 4)},\n'
                 f'        sampling_rate: {le(b, o + 4, 4)},\n'
                 f'        bitrate_range: {le(b, o + 8, 4)},\n'
                 f'        sbr_mode: {b[o + 12]},\n'
                 f'        ch_mode: {le(b, o + 16, 4, True)},\n    }},\n')
    out = header(src, 'The file-static tables of `aacenc_lib.cpp`.',
                 '\nuse super::EldSbrConfigurator;\n')
    out += (f'\n/// `eldSbrAutoConfigTab`: ELD/SBR default configurations.\n///\n'
            f'/// Generated with {cmd(src, "eldSbrAutoConfigTab", "UCHAR")}\n'
            f'/// (decoded as three `ULONG`s, `UCHAR sbrMode`, three padding bytes and\n'
            f'/// `CHANNEL_MODE chMode`).\n'
            f'pub(super) static ELD_SBR_AUTO_CONFIG_TAB: [EldSbrConfigurator; {len(b) // 20}] = [\n'
            + ents + '];\n')
    write(os.path.join(SRCDIR, 'aacenc_lib', 'tables.rs'), out)


def main():
    gen_aacenc()
    gen_metadata_main()
    gen_mps_main()
    gen_aacenc_lib()


if __name__ == '__main__':
    main()
