#!/usr/bin/env python3
"""Generate crates/aacenc/src/adj_thr/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped: the names of the tables and of
the scalar constants are taken from libAACenc/src/adj_thr.cpp. BIT_PE_SFAC tables are dumped as
LONG (bitrate followed by bits2PeFactor[2][2]); the entries of bits2PeConfigTab hold a pointer,
so their sampleRate fields are dumped one by one and the pointer is matched by name.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacenc/src/adj_thr/gen_tables.py [-j JOBS]
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402  (for the location of the C++ sources)

SRC = 'libAACenc/src/adj_thr.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libAACenc/src/adj_thr.cpp.
//
// GENERATED by `python3 crates/aacenc/src/adj_thr/gen_tables.py`; do not edit. Every value is
// dumped with scripts/dump_table.py (the command is given at each item), which checks that the
// arm64 and x86_64 builds give the same values.

//! The file-local constant tables of `adj_thr.cpp`.

use super::{BitPeSfac, Bits2PeCfgTab};
use fdk_aac_rs_fdk::common_fix::FixpDbl;
'''


def rust_name(c):
    """Mechanical SCREAMING_SNAKE_CASE name of a C table."""
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'([A-Za-z])(\d)', r'\1_\2', s)
    s = re.sub(r'(\d)([A-Za-z])', r'\1_\2', s)
    s = re.sub(r'_+', '_', s)
    return s.upper().strip('_')


def dump(symbol, elemtype, count=None):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    if count is not None:
        cmd += ['--count', str(count)]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def hx(v):
    return f'0x{v & 0xFFFFFFFF:08X}' + ('u32 as i32' if v < 0 else '')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()
    src = open(os.path.join(dump_table.CDIR, SRC)).read()

    arrays = re.findall(r'^static const FIXP_DBL (\w+)\[\w+\]\s*=', src, re.M)
    scalars = re.findall(r'^static const FIXP_DBL (\w+)\s*=', src, re.M)
    pe_tabs = re.findall(r'^static const BIT_PE_SFAC (\w+)\[\]\s*=', src, re.M)
    cfg = re.search(r'bits2PeConfigTab\[\]\s*=\s*\{(.*?)\};', src, re.S).group(1)
    cfg_tabs = re.findall(r'\{\s*\d+,\s*(\w+),', cfg)
    assert arrays == ['invInt', 'invSqrt4'], arrays
    assert len(scalars) == 7, scalars
    assert cfg_tabs == pe_tabs, (cfg_tabs, pe_tabs)

    jobs = [(n, 'LONG', None) for n in arrays]
    jobs += [(f'&{n}', 'LONG', 1) for n in scalars]
    jobs += [(n, 'LONG', None) for n in pe_tabs]
    jobs += [(f'&bits2PeConfigTab[{i}].sampleRate', 'LONG', 1) for i in range(len(cfg_tabs))]
    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        vals = list(ex.map(lambda j: dump(*j), jobs))
    vals.reverse()

    out = HEADER
    for n in arrays:
        v = vals.pop()
        out += (f'\n/// `{n}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {n} LONG`.\n'
                f'pub static {rust_name(n)}: [FixpDbl; {len(v)}] = [\n    '
                + ', '.join(hx(x) for x in v) + ',\n];\n')
    for n in scalars:
        v = vals.pop()
        out += (f'\n/// `{n}`\n///\n/// Generated with `scripts/dump_table.py {SRC} \'&{n}\' LONG '
                f'--count 1`.\npub const {rust_name(n)}: FixpDbl = {hx(v[0])};\n')
    for n in pe_tabs:
        v = vals.pop()
        assert len(v) % 5 == 0, (n, len(v))
        rows = ''
        for i in range(0, len(v), 5):
            e = v[i:i + 5]
            rows += (f'    BitPeSfac {{\n        bitrate: {e[0]},\n        bits2_pe_factor: '
                     f'[[{hx(e[1])}, {hx(e[2])}], [{hx(e[3])}, {hx(e[4])}]],\n    }},\n')
        out += (f'\n/// `{n}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {n} LONG`.\n'
                f'pub static {rust_name(n)}: [BitPeSfac; {len(v) // 5}] = [\n{rows}];\n')
    rates = [vals.pop()[0] for _ in cfg_tabs]
    rows = ''.join(f'    Bits2PeCfgTab {{ sample_rate: {r}, p_pe_tab: &{rust_name(t)} }},\n'
                   for r, t in zip(rates, cfg_tabs))
    out += (f'\n/// `bits2PeConfigTab` (`nEntries` is the length of `pPeTab`)\n///\n/// The sample '
            f'rates are generated with `scripts/dump_table.py {SRC} '
            f'\'&bits2PeConfigTab[i].sampleRate\' LONG --count 1`.\n'
            f'pub static BITS2_PE_CONFIG_TAB: [Bits2PeCfgTab; {len(rates)}] = [\n{rows}];\n')
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)
    print(f'{len(arrays)} arrays, {len(scalars)} constants, {len(pe_tabs)} bits2pe tables')


if __name__ == '__main__':
    main()
