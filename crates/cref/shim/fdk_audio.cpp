/* LIB_VERSION_STRING with the library's FDKsprintf; writes 32 bytes to str. */
void cref_LIB_VERSION_STRING(INT version, char *str) {
  LIB_INFO info;
  FDKmemclear(&info, sizeof(info));
  info.version = version;
  LIB_VERSION_STRING(&info);
  FDKmemcpy(str, info.versionStr, sizeof(info.versionStr));
}

/* A LIB_INFO table of FDK_MODULE_LAST entries from module ids and flags; returns the results of
   FDKlibInfo_getCapabilities and FDKlibInfo_lookup for module_id, and the module ids after
   FDKinitLibInfo in ids_after_init. */
void cref_libinfo(const INT *ids, const UINT *flags, INT module_id, UINT *caps, INT *lookup, INT *ids_after_init) {
  LIB_INFO info[FDK_MODULE_LAST];
  for (int i = 0; i < FDK_MODULE_LAST; i++) {
    FDKmemclear(&info[i], sizeof(LIB_INFO));
    info[i].module_id = (FDK_MODULE_ID)ids[i];
    info[i].flags = flags[i];
  }
  *caps = FDKlibInfo_getCapabilities(info, (FDK_MODULE_ID)module_id);
  *lookup = FDKlibInfo_lookup(info, (FDK_MODULE_ID)module_id);
  FDKinitLibInfo(info);
  for (int i = 0; i < FDK_MODULE_LAST; i++) ids_after_init[i] = info[i].module_id;
}

