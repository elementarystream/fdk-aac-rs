#[test]
fn poisoned_scratch_reference_pair() {
    // Measurement (PORTING.md, "Memory"): two reference decoders decode the same stream, one
    // with its scratch buffers (workBufferCore1/2, pTimeData2, the elements' pWorkBufferCore1)
    // poisoned before every call; the outputs (return value, whole output buffer, stream info)
    // are compared. Differences are reported, not failures: the port reuses the buffers like the
    // reference (checked by poisoned_scratch_buffers).
    let mut streams: Vec<(String, Vec<u8>, Vec<Vec<u8>>)> = Vec::new();
    for rel in [
        "conformance/14496-26/compressedMp4/al04_48.mp4",
        "conformance/14496-26/compressedMp4/al06_44.mp4",
        "conformance/14496-26/compressedMp4/al17_44.mp4",
        "conformance/14496-26/compressedMp4/er_al21_48_ep0.mp4",
        "conformance/14496-26/compressedMp4/er_ad6000np_44_ep0.mp4",
        "conformance/14496-26/compressedMp4/er_eld1000np_32_ep0.mp4",
        "conformance/23003-7/compressedMp4/Lpd_1_c0_Ace_0x1b.mp4",
        "conformance/23003-7/compressedMp4/Cct_1_c0_CAc_0x08.mp4",
        "conformance/23003-7/compressedMp4/Fd_1_c1_Sfb_0x0c.mp4",
    ] {
        if let Some((a, aus)) = demux(rel) {
            streams.push((rel.to_string(), a, aus));
        }
    }
    let (mut frames, mut differing) = (0, 0);
    for (name, asc, aus) in &streams {
        for pat in [0x00u8, 0xA5, 0xFF] {
            let a = unsafe { c::cref_aacdecoder_lib_open(TT_MP4_RAW, 1) };
            let b = unsafe { c::cref_aacdecoder_lib_open(TT_MP4_RAW, 1) };
            let mut asc2 = asc.clone();
            unsafe {
                c::cref_aacdecoder_lib_config_raw(a, asc2.as_mut_ptr(), asc.len() as u32);
                c::cref_aacdecoder_lib_config_raw(b, asc2.as_mut_ptr(), asc.len() as u32);
            }
            let mut first = None;
            for (k, au) in aus.iter().take(60).enumerate() {
                let flags = [0, 0, 0, AACDEC_CONCEAL, 0, AACDEC_FLUSH, 0, 0][k % 8];
                let mut outs = Vec::new();
                for (h, poison) in [(a, false), (b, true)] {
                    let mut d = au.clone();
                    let mut v = d.len() as u32;
                    unsafe { c::cref_aacdecoder_lib_fill(h, d.as_mut_ptr(), d.len() as u32, &mut v) };
                    if poison {
                        unsafe { c::cref_aacdecoder_lib_poison(h, pat) };
                    }
                    let mut out = vec![0i16; 16384];
                    let r = unsafe { c::cref_aacdecoder_lib_decode(h, out.as_mut_ptr(), 16384, flags) };
                    let mut si = [0i32; 64];
                    unsafe { c::cref_aacdecoder_lib_stream_info(h, si.as_mut_ptr()) };
                    outs.push((r, out, si));
                }
                frames += 1;
                if outs[0] != outs[1] {
                    differing += 1;
                    first.get_or_insert(k);
                }
            }
            if let Some(k) = first {
                eprintln!("{name}: poison {pat:#x}: first difference in call {k}");
            }
            unsafe {
                c::cref_aacdecoder_lib_close(a);
                c::cref_aacdecoder_lib_close(b);
            }
        }
    }
    eprintln!("poisoned_scratch_reference_pair: {differing} of {frames} reference calls differ");
}

