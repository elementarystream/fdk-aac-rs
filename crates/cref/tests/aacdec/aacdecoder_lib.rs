/// Mutates `data` (bit flips, byte runs, truncation, duplication) deterministically.
fn mutate(data: &[u8], rng: &mut Rng) -> Vec<u8> {
    let mut d = data.to_vec();
    match rng.next_u32() % 4 {
        0 => {
            for _ in 0..1 + rng.next_u32() % 20 {
                if d.is_empty() {
                    break;
                }
                let i = (rng.next_u32() as usize) % d.len();
                d[i] ^= 1 << (rng.next_u32() % 8);
            }
        }
        1 => {
            if !d.is_empty() {
                let i = (rng.next_u32() as usize) % d.len();
                let n = (rng.next_u32() as usize % 64).min(d.len() - i);
                let v = rng.next_u32() as u8;
                d[i..i + n].fill(v);
            }
        }
        2 => {
            let n = (rng.next_u32() as usize) % (d.len() + 1);
            d.truncate(n);
        }
        _ => {
            if d.len() > 2 {
                let i = (rng.next_u32() as usize) % d.len();
                let j = (rng.next_u32() as usize) % d.len();
                let (a, b) = (i.min(j), i.max(j));
                let piece = d[a..b].to_vec();
                d.splice(b..b, piece);
            }
        }
    }
    d
}

