/// Decodes an encoded stream through its transport (packets for raw/LATM MCP0, a stream
/// otherwise).
fn decode_encoded(name: &str, tt: i32, asc: &[u8], aus: &[Vec<u8>], cfg: bool, setup: impl Fn(&mut Pair), flags_at: impl FnMut(usize) -> u32) -> (usize, usize) {
    let mut pair = Pair::open(tt, 1, name).unwrap();
    if cfg {
        pair.config_raw(asc);
    }
    setup(&mut pair);
    if tt == TT_MP4_RAW || tt == TT_MP4_LATM_MCP0 || tt == TT_MP4_LATM_MCP1 {
        let refs: Vec<&[u8]> = aus.iter().map(|a| a.as_slice()).collect();
        run_packets(&mut pair, &refs, 400, flags_at);
    } else {
        let data: Vec<u8> = aus.concat();
        run_stream(&mut pair, &data, &[2000, 4096], 400, tt == TT_MP4_ADIF, flags_at);
    }
    (pair.n_valid, pair.n_anc)
}

