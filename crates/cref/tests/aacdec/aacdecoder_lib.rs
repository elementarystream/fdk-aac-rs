/// A stream generated by the reference encoder: (ASC, access units).
pub fn encode(channels: i32, rate: i32, params: &[(i32, i32)], meta: Option<[i32; 12]>, anc: bool, frames: i32) -> Option<(Vec<u8>, Vec<Vec<u8>>)> {
    let mut p: Vec<i32> = params.iter().flat_map(|&(a, b)| [a, b]).collect();
    let mut m = meta.unwrap_or([0; 12]);
    let mut out = vec![0u8; 4 << 20];
    let mut au = vec![0i32; 4096];
    let mut asc = vec![0u8; 1024];
    let mut asclen = 0;
    let n = unsafe {
        c::cref_aacdecoder_lib_encode(
            channels,
            rate,
            p.as_mut_ptr(),
            params.len() as i32,
            m.as_mut_ptr(),
            if meta.is_some() { 12 } else { 0 },
            anc as i32,
            frames,
            out.as_mut_ptr(),
            out.len() as i32,
            au.as_mut_ptr(),
            au.len() as i32,
            asc.as_mut_ptr(),
            &mut asclen,
        )
    };
    if n <= 0 {
        return None;
    }
    let mut v = Vec::new();
    let mut pos = 0usize;
    for &s in &au[..n as usize] {
        v.push(out[pos..pos + s as usize].to_vec());
        pos += s as usize;
    }
    asc.truncate(asclen as usize);
    Some((asc, v))
}

pub const AOT: i32 = 0x0100;
pub const BITRATE: i32 = 0x0101;
