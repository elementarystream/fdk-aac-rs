/// The USAC conformance MP4 files whose names match `pred`, sorted.
pub fn usac_mp4(pred: impl Fn(&str) -> bool) -> Vec<String> {
    let dir = work_dir().join("conformance/23003-7/compressedMp4");
    let mut v: Vec<String> = std::fs::read_dir(&dir)
        .map(|d| {
            d.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.ends_with(".mp4") && pred(n))
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v.into_iter().map(|n| format!("conformance/23003-7/compressedMp4/{n}")).collect()
}

/// Adds the frame counts of a pair (valid, SBR, PS, MPS).
fn count(c: [usize; 4], p: &Pair) -> [usize; 4] {
    [c[0] + p.n_valid, c[1] + p.n_sbr, c[2] + p.n_ps, c[3] + p.n_mps]
}

fn report(c: [usize; 4]) -> String {
    format!("{} valid frames, {} with SBR, {} with PS, {} with MPS", c[0], c[1], c[2], c[3])
}

/// Packet decoding of a demuxed MP4 file with a setup (SetParam calls) and decode flags; returns
/// the pair for further checks.
fn run_mp4_with(
    rel: &str,
    max_dec: usize,
    poison: Option<u8>,
    setup: impl Fn(&mut Pair),
    flags_at: impl FnMut(usize) -> u32,
) -> Option<Pair> {
    let (asc, aus) = demux(rel)?;
    let mut pair = Pair::open(TT_MP4_RAW, 1, rel).unwrap();
    pair.poison = poison;
    setup(&mut pair);
    pair.config_raw(&asc);
    let refs: Vec<&[u8]> = aus.iter().map(|a| a.as_slice()).collect();
    run_packets(&mut pair, &refs, max_dec, flags_at);
    Some(pair)
}

