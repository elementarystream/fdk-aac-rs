/// A reference decoder and a port decoder driven in lockstep.
pub struct Pair {
    api: Api,
    r: *mut c_void,
    p: Option<Box<AacDecoderInstance>>,
    out_size: i32,
    out_r: Vec<i16>,
    out_p: Vec<i16>,
    anc_r: Vec<u8>,
    anc: bool,
    /// Byte pattern written into the scratch buffers of both decoders before every DecodeFrame
    /// call (PORTING.md, "Memory"), if any.
    pub poison: Option<u8>,
    pub ctx: String,
    pub n_dec: usize,
    pub n_valid: usize,
    pub n_anc: usize,
    /// Valid frames with SBR output (`AC_SBR_PRESENT` in the port's flags), with PS output and
    /// with MPEG Surround (`AC_MPS_PRESENT` or `mpsEnableCurr`).
    pub n_sbr: usize,
    pub n_ps: usize,
    pub n_mps: usize,
}

impl Drop for Pair {
    fn drop(&mut self) {
        if !self.r.is_null() {
            unsafe { (self.api.close)(self.r) };
        }
        aac_decoder_close(self.p.take());
    }
}

impl Pair {
    pub fn open(tt: i32, layers: u32, ctx: &str) -> Option<Pair> {
        Self::open_with(REF, tt, layers, ctx)
    }

    pub fn open_with(api: Api, tt: i32, layers: u32, ctx: &str) -> Option<Pair> {
        let r = unsafe { (api.open)(tt, layers) };
        let p = aac_decoder_open(tt, layers);
        assert_eq!(r.is_null(), p.is_none(), "{ctx}: open({tt}, {layers})");
        if r.is_null() {
            return None;
        }
        Some(Pair {
            api,
            r,
            p,
            out_size: 65536,
            out_r: vec![0; 65536],
            out_p: vec![0; 65536],
            anc_r: Vec::new(),
            anc: false,
            poison: None,
            ctx: ctx.to_string(),
            n_dec: 0,
            n_valid: 0,
            n_anc: 0,
            n_sbr: 0,
            n_ps: 0,
            n_mps: 0,
        })
    }

    pub fn raw(&self) -> *mut c_void {
        self.r
    }

    pub fn port(&self) -> &AacDecoderInstance {
        self.p.as_deref().unwrap()
    }

    fn h(&mut self) -> &mut AacDecoderInstance {
        self.p.as_deref_mut().unwrap()
    }

    pub fn set_out_size(&mut self, n: i32) {
        self.out_size = n;
        self.out_r = vec![0; n as usize];
        self.out_p = vec![0; n as usize];
    }

    pub fn config_raw(&mut self, asc: &[u8]) -> i32 {
        let mut a = asc.to_vec();
        let rr = unsafe { (self.api.config_raw)(self.r, a.as_mut_ptr(), a.len() as u32) };
        let rp = aac_decoder_config_raw(self.h(), &[asc], &[asc.len() as u32]);
        assert_eq!(rr, rp, "{}: config_raw", self.ctx);
        self.check_si("config_raw");
        rr
    }

    pub fn set_param(&mut self, param: i32, value: i32) -> i32 {
        let rr = unsafe { (self.api.set_param)(self.r, param, value) };
        let rp = aac_decoder_set_param(self.p.as_deref_mut(), param, value);
        assert_eq!(rr, rp, "{}: set_param({param:#x}, {value})", self.ctx);
        rr
    }

    pub fn anc_init(&mut self, size: i32) {
        self.anc_r = vec![0u8; size.max(0) as usize];
        let rr = unsafe { (self.api.anc_init)(self.r, self.anc_r.as_mut_ptr(), size) };
        let rp = aac_decoder_anc_data_init(
            self.h(),
            Some(vec![0u8; size.max(0) as usize].into_boxed_slice()),
            size,
        );
        assert_eq!(rr, rp, "{}: anc_init", self.ctx);
        self.anc = rr == 0;
    }

    /// GetFreeBytes, then Fill with `data`; returns the bytes consumed.
    pub fn fill(&mut self, data: &[u8]) -> u32 {
        let mut fr = 0u32;
        let rr = unsafe { (self.api.free_bytes)(self.r, &mut fr) };
        let mut fp = 0u32;
        let rp = aac_decoder_get_free_bytes(self.p.as_deref_mut(), &mut fp);
        assert_eq!((rr, fr), (rp, fp), "{}: get_free_bytes", self.ctx);
        let mut d = data.to_vec();
        let mut vr = data.len() as u32;
        let rr = unsafe { (self.api.fill)(self.r, d.as_mut_ptr(), d.len() as u32, &mut vr) };
        let mut vp = [data.len() as u32];
        let rp = aac_decoder_fill(self.h(), &[data], &[data.len() as u32], &mut vp);
        assert_eq!((rr, vr), (rp, vp[0]), "{}: fill", self.ctx);
        data.len() as u32 - vr
    }

    fn check_si(&mut self, what: &str) {
        let mut o = [0i32; 64];
        let n = unsafe { (self.api.stream_info)(self.r, o.as_mut_ptr()) };
        let sp = si_port(aac_decoder_get_stream_info(self.p.as_deref()).unwrap());
        assert_eq!(&o[..n as usize], &sp[..], "{}: stream info after {what} (call {})", self.ctx, self.n_dec);
    }

    fn poison_buffers(&mut self, pat: u8) {
        unsafe { (self.api.poison)(self.r, pat) };
        let v = i32::from_ne_bytes([pat; 4]);
        let h = self.h();
        if let Some(w) = h.work_buffer_core1.as_deref_mut() {
            w.buf.fill(v);
        }
        if let Some(w) = h.work_buffer_core2.as_deref_mut() {
            w.fill(v);
        }
        if let Some(w) = h.p_time_data2.as_deref_mut() {
            w.fill(v);
        }
        if let Some(w) = h.p_work_buffer_core1.as_deref_mut() {
            w.buf.fill(v);
        }
    }

    /// DecodeFrame on both; compares the return value, the whole output buffer, the stream info
    /// and the ancillary data. Returns the return value.
    pub fn decode(&mut self, flags: u32) -> i32 {
        let n = self.out_size as usize;
        for i in 0..n {
            let x = ((i as u32).wrapping_mul(40503).wrapping_add(0x6A5D) | 1) as i16;
            self.out_r[i] = x;
            self.out_p[i] = x;
        }
        if let Some(pat) = self.poison {
            self.poison_buffers(pat);
        }
        let rr = unsafe { (self.api.decode)(self.r, self.out_r.as_mut_ptr(), self.out_size, flags) };
        let out_size = self.out_size;
        let mut out_p = std::mem::take(&mut self.out_p);
        let rp = aac_decoder_decode_frame(self.p.as_deref_mut(), &mut out_p, out_size, flags);
        self.out_p = out_p;
        assert_eq!(rr, rp, "{}: decode_frame ret (call {}, flags {flags})", self.ctx, self.n_dec);
        if self.out_r != self.out_p {
            let i = self.out_r.iter().zip(&self.out_p).position(|(a, b)| a != b).unwrap();
            panic!(
                "{}: decode_frame output (call {}, ret {rr:#x}): first difference at sample {i}: {} vs {}",
                self.ctx, self.n_dec, self.out_r[i], self.out_p[i]
            );
        }
        self.check_si("decode_frame");
        // The internal time data buffer pTimeData2 (the core output, the PCM post processing
        // and the joint stereo scratch data) must match as well.
        {
            let td_p = self.p.as_deref().unwrap().p_time_data2.as_deref().unwrap_or(&[]);
            let mut td_r = vec![0i32; td_p.len()];
            unsafe { (self.api.time_data2)(self.r, td_r.as_mut_ptr(), td_p.len() as i32) };
            if td_r != td_p {
                let i = td_r.iter().zip(td_p).position(|(a, b)| a != b).unwrap();
                panic!("{}: pTimeData2 after decode_frame (call {}, ret {rr:#x}): first difference at {i}: {} vs {}", self.ctx, self.n_dec, td_r[i], td_p[i]);
            }
        }
        if is_output_valid(rr) != 0 {
            self.n_valid += 1;
            let d = self.port();
            let (fl, si) = (d.flags[0], &d.stream_info);
            // (USAC signals MPS212 per element; AC_PS_PRESENT is not set for every frame with
            // PS output: also count mono cores with stereo output without MPEG Surround)
            let mps = fl & AC_MPS_PRESENT != 0 || d.mps_enable_curr != 0;
            let ps = fl & AC_PS_PRESENT != 0
                || (!mps && si.aac_num_channels == 1 && si.num_channels == 2);
            self.n_sbr += (fl & AC_SBR_PRESENT != 0) as usize;
            self.n_ps += ps as usize;
            self.n_mps += mps as usize;
            if self.anc {
                for idx in 0..18 {
                    let (mut off_r, mut size_r) = (0i32, 0i32);
                    let r = unsafe {
                        (self.api.anc_get)(self.r, idx, self.anc_r.as_mut_ptr(), &mut off_r, &mut size_r)
                    };
                    let mut off_p = None;
                    let mut size_p = 0;
                    let p = aac_decoder_anc_data_get(self.p.as_deref().unwrap(), idx, &mut off_p, &mut size_p);
                    let off_p = off_p.map_or(-1, |o| o as i32);
                    assert_eq!((r, off_r, size_r), (p, off_p, size_p), "{}: anc_data_get {idx}", self.ctx);
                    if size_r > 0 && off_r >= 0 {
                        self.n_anc += 1;
                        let a = &self.anc_r[off_r as usize..(off_r + size_r) as usize];
                        let b = aac_decoder_anc_data_buffer(self.p.as_deref().unwrap()).unwrap();
                        assert_eq!(a, &b[off_p as usize..(off_p + size_p) as usize], "{}: anc data", self.ctx);
                    }
                    if r != 0 || size_r <= 0 {
                        break;
                    }
                }
            }
        }
        self.n_dec += 1;
        rr
    }

    /// Decodes until NOT_ENOUGH_BITS (at most `max` calls).
    pub fn decode_loop(&mut self, max: usize, mut flags_at: impl FnMut(usize) -> u32) {
        for _ in 0..max {
            let f = flags_at(self.n_dec);
            let r = self.decode(f);
            if r == AAC_DEC_NOT_ENOUGH_BITS {
                break;
            }
        }
    }
}

/// Stream input: fills `data` in chunks of the cyclic fill sizes, decoding after each fill.
pub fn run_stream(pair: &mut Pair, data: &[u8], fill_sizes: &[u32], max_dec: usize, once: bool, mut flags_at: impl FnMut(usize) -> u32) {
    let mut pos = 0usize;
    let mut k = 0;
    let mut zero = 0;
    while pos < data.len() && pair.n_dec < max_dec {
        let fs = fill_sizes[k % fill_sizes.len()] as usize;
        k += 1;
        let chunk = (data.len() - pos).min(fs);
        let used = pair.fill(&data[pos..pos + chunk]) as usize;
        pos += used;
        if used == 0 {
            zero += 1;
            if zero >= 2 {
                break;
            }
        } else {
            zero = 0;
        }
        if once {
            let f = flags_at(pair.n_dec);
            pair.decode(f);
        } else {
            pair.decode_loop(max_dec.saturating_sub(pair.n_dec).min(1000), &mut flags_at);
        }
    }
    pair.decode_loop(max_dec.saturating_sub(pair.n_dec).min(64), &mut flags_at);
}

/// Packet input: one Fill and one DecodeFrame per access unit.
pub fn run_packets(pair: &mut Pair, aus: &[&[u8]], max_dec: usize, mut flags_at: impl FnMut(usize) -> u32) {
    for au in aus {
        if pair.n_dec >= max_dec {
            break;
        }
        pair.fill(au);
        let f = flags_at(pair.n_dec);
        pair.decode(f);
    }
}

/// Demuxes an MP4 file of the conformance material into (ASC, access units).
pub fn demux(rel: &str) -> Option<(Vec<u8>, Vec<Vec<u8>>)> {
    let data = read(rel)?;
    let t = mp4demux::mp4_demux(&data, 0).ok()?;
    let asc = t.asc(&data).to_vec();
    let aus = t
        .samples
        .iter()
        .map(|s| data[s.offset as usize..s.offset as usize + s.size as usize].to_vec())
        .collect();
    Some((asc, aus))
}

fn run_mp4(rel: &str, max_dec: usize, poison: Option<u8>) -> bool {
    let Some((asc, aus)) = demux(rel) else {
        return false;
    };
    let mut pair = Pair::open(TT_MP4_RAW, 1, rel).unwrap();
    pair.poison = poison;
    pair.config_raw(&asc);
    let refs: Vec<&[u8]> = aus.iter().map(|a| a.as_slice()).collect();
    run_packets(&mut pair, &refs, max_dec, |_| 0);
    true
}

/// The conformance MP4 files whose names match `pred`, sorted.
pub fn conformance_mp4(pred: impl Fn(&str) -> bool) -> Vec<String> {
    let dir = work_dir().join("conformance/14496-26/compressedMp4");
    let mut v: Vec<String> = std::fs::read_dir(&dir)
        .map(|d| {
            d.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.ends_with(".mp4") && pred(n))
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v.into_iter().map(|n| format!("conformance/14496-26/compressedMp4/{n}")).collect()
}

/// Every n-th entry of a list (a deterministic subset).
pub fn every<T: Clone>(v: &[T], n: usize) -> Vec<T> {
    v.iter().step_by(n.max(1)).cloned().collect()
}

#[test]
fn conformance_aac_lc_mp4() {
    // AAC-LC (incl. multichannel with PCE, 960 frames) without SBR.
    let files = conformance_mp4(|n| {
        n.starts_with("al") && n.as_bytes().get(2).is_some_and(|c| c.is_ascii_digit()) && !n.contains("sbr")
    });
    let files = every(&files, 3);
    let mut ran = 0;
    for f in &files {
        if run_mp4(f, 60, None) {
            ran += 1;
        }
    }
    eprintln!("conformance_aac_lc_mp4: {ran} of {} streams", files.len());
}

