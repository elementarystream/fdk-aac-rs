pub fn work_dir() -> PathBuf {
    if let Ok(d) = std::env::var("FDK_AAC_RS_WORK_DIR") {
        return PathBuf::from(d);
    }
    let out = std::process::Command::new("git")
        .args(["rev-parse", "--path-format=absolute", "--git-common-dir"])
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .output()
        .expect("git");
    let common = PathBuf::from(String::from_utf8_lossy(&out.stdout).trim().to_string());
    common.parent().unwrap().join("work")
}

pub fn read(rel: &str) -> Option<Vec<u8>> {
    std::fs::read(work_dir().join(rel)).ok()
}

/// The port's CStreamInfo in the order of `cref_aacdecoder_lib_stream_info`.
fn si_port(si: &CStreamInfo) -> Vec<i32> {
    let mut o = vec![si.sample_rate, si.frame_size, si.num_channels];
    o.extend(si.p_channel_type.iter().copied());
    o.extend(si.p_channel_indices.iter().map(|&x| x as i32));
    o.extend([
        si.aac_sample_rate,
        si.profile,
        si.aot,
        si.channel_config,
        si.bit_rate,
        si.aac_samples_per_frame,
        si.aac_num_channels,
        si.ext_aot,
        si.ext_sampling_rate,
        si.output_delay as i32,
        si.flags as i32,
        si.ep_config as i32,
        si.num_lost_access_units,
    ]);
    for v in [si.num_total_bytes, si.num_bad_bytes, si.num_total_access_units, si.num_bad_access_units] {
        o.push(v as i32);
        o.push((v >> 32) as i32);
    }
    o.extend([si.drc_prog_ref_lev as i32, si.drc_pres_mode as i32, si.output_loudness]);
    o
}


/// The C decoder a [`Pair`] compares the port with: the reference library, or the stubbed
