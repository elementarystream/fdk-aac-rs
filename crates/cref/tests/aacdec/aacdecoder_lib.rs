// Differential tests of fdk_aac_rs_aacdec::aacdecoder_lib against the C++ reference: the whole
// decoder through its public API (PORTING.md, "Definition of bit-exact"). The same call sequence
// goes through the reference (cref_aacDecoder_*) and the port; every return value, every sample
// of the whole output buffer, the complete CStreamInfo, the free bytes, the bytes consumed by
// Fill and the ancillary data are compared after every call.
//
// Streams: the ISO conformance material in work/conformance (MP4 demuxed with the CLI's demuxer,
// ADTS, ADIF, LOAS), the real-world streams in work/rw, and streams generated by the reference
// encoder (LATM, ADIF, ADTS with CRC, raw, LD, ELD, multichannel, metadata and ancillary data).
// Missing material is skipped (the tests report what they ran).

