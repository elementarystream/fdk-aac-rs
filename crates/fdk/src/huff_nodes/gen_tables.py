#!/usr/bin/env python3
"""Generate crates/fdk/src/huff_nodes/tables.rs from the C++ reference.

Every node table of libFDK/src/huff_nodes.cpp is dumped with scripts/dump_table.py (as SHORT values
in memory order), which compiles the C++ source on arm64 and x86_64 and fails if the two give
different values. Nothing is retyped: the list of tables (name and struct type) is taken from the
definitions in huff_nodes.cpp, the field layout of each struct type from huff_nodes.h. The
pointer tables (FDK_huffICCNodes, FDK_huffCLDNodes, huffOLDNodes), which reference the node
tables, are written by hand in huff_nodes.rs and checked by the differential test.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/fdk/src/huff_nodes/gen_tables.py [-j JOBS]
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402  (for the location of the C++ sources)

SRC = 'libFDK/src/huff_nodes.cpp'
HDR = 'libFDK/include/huff_nodes.h'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libFDK/src/huff_nodes.cpp.
//
// GENERATED by `python3 crates/fdk/src/huff_nodes/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.
'''


def rust_type(c):
    """HUFF_CLD_NOD_1D -> HuffCldNod1d, HUFF_NRG_NOD_2D_df -> HuffNrgNod2dDf"""
    return ''.join(p[:1].upper() + p[1:].lower() for p in c.split('_'))


def rust_field(c):
    """nodeTab -> node_tab, h1D -> h1d"""
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    return s.lower()


def rust_name(c):
    """FDK_huffICCNodes_h1D_0 -> FDK_HUFF_ICC_NODES_H1D_0"""
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'(\d)([A-Z])', r'\1_\2', s)
    return s.upper().replace('H1_D', 'H1D').replace('H2_D', 'H2D')


def structs(hdr):
    """typedef struct { ... } NAME; -> {NAME: [(field, type, dims)]} for the SHORT node structs
    and the structs of node structs (by value)."""
    out = {}
    for body, name in re.findall(r'typedef struct \{(.*?)\}\s*(\w+);', hdr, re.S):
        fields = []
        ok = True
        for decl in body.split(';'):
            decl = re.sub(r'/\*.*?\*/', '', decl, flags=re.S).strip()
            if not decl:
                continue
            m = re.fullmatch(r'(\w+)\s+(\w+)((?:\[\d+\])*)', decl)
            if not m:
                ok = False  # pointer members: written by hand
                break
            dims = [int(d) for d in re.findall(r'\[(\d+)\]', m.group(3))]
            fields.append((m.group(2), m.group(1), dims))
        if ok:
            out[name] = fields
    return out


def size(t, st):
    """Number of SHORT values of type t."""
    if t == 'SHORT':
        return 1
    n = 0
    for _, ft, dims in st[t]:
        k = size(ft, st)
        for d in dims:
            k *= d
        n += k
    return n


def literal(t, vals, st, indent):
    """Rust literal of a value of type t from the flat SHORT values."""
    pad = ' ' * indent
    if t == 'SHORT':
        return str(vals[0])
    out = f'{rust_type(t)} {{\n'
    pos = 0
    for f, ft, dims in st[t]:
        k = size(ft, st)
        n = k
        for d in dims:
            n *= d
        v = vals[pos:pos + n]
        pos += n
        if ft == 'SHORT':
            assert dims[-1] == 2 and len(dims) == 2, (t, f)
            pairs = [f'[{v[i]}, {v[i + 1]}]' for i in range(0, len(v), 2)]
            body = ''.join(f'{pad}        ' + ', '.join(pairs[i:i + 6]) + ',\n'
                           for i in range(0, len(pairs), 6))
            out += f'{pad}    {rust_field(f)}: [\n{body}{pad}    ],\n'
        else:
            def arr(v, dims):
                if not dims:
                    return literal(ft, v, st, indent + 8)
                step = len(v) // dims[0]
                return '[' + ', '.join(arr(v[i * step:(i + 1) * step], dims[1:])
                                       for i in range(dims[0])) + ']'
            out += f'{pad}    {rust_field(f)}: {arr(v, dims)},\n'
    assert pos == len(vals), (t, pos, len(vals))
    return out + f'{pad}}}'


def dump(symbol):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, 'SHORT']
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()
    src = open(os.path.join(dump_table.CDIR, SRC)).read()
    hdr = open(os.path.join(dump_table.CDIR, HDR)).read()
    st = structs(hdr)

    tables = [(t, n, s) for s, t, n in
              re.findall(r'^(static )?const (\w+) (\w+)\s*=', src, re.M) if t in st]
    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        vals = list(ex.map(lambda t: dump(t[1]), tables))

    out = HEADER + '''
//! The node tables of `huff_nodes.cpp`.

use super::*;
'''
    for (t, name, static), v in zip(tables, vals):
        assert len(v) == size(t, st), name
        vis = 'pub'
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} SHORT`.\n'
                f'#[rustfmt::skip]\n{vis} static {rust_name(name)}: {rust_type(t)} = '
                f'{literal(t, v, st, 0)};\n')
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)
    print(f'{len(tables)} tables')


if __name__ == '__main__':
    main()
