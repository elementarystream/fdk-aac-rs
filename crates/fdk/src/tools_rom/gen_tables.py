#!/usr/bin/env python3
"""Generate crates/fdk/src/tools_rom/{tables,element_lists}.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles the C++ source on arm64 and x86_64
and fails if the two give different values. Nothing is retyped:

* The list of tables (name and element type) is taken from the definitions in
  libFDK/src/FDK_tools_rom.cpp. FIXP_STP/FIXP_WTP tables (FIXP_SPK) are dumped as SHORT pairs
  and wrapped into `spk(re, im)`; the other tables are dumped with their scalar type.
* The `rbd_id_t` enumerators are taken from libFDK/include/FDK_tools_rom.h; the element lists
  (`static const rbd_id_t el_*[]`, `list_*[]`) are dumped as INT and written with the names of
  their values. The pointer structure of the element lists (`element_list_t` nodes) is rebuilt
  by hand in tools_rom.rs and checked by the differential test.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/fdk/src/tools_rom/gen_tables.py [-j JOBS]
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402  (for the location of the C++ sources)

SRC = 'libFDK/src/FDK_tools_rom.cpp'
HDR = 'libFDK/include/FDK_tools_rom.h'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libFDK/src/FDK_tools_rom.cpp.
//
// GENERATED by `python3 crates/fdk/src/tools_rom/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.
'''

# C element type -> (dump type, Rust element type, pairs)
TYPES = {
    'FIXP_STP': ('SHORT', 'FixpStp', True),
    'FIXP_WTP': ('SHORT', 'FixpWtp', True),
    'FIXP_STB': ('SHORT', 'FixpStb', False),
    'FIXP_PFT': ('SHORT', 'FixpPft', False),
    'FIXP_QTW': ('SHORT', 'FixpQtw', False),
    'USHORT': ('USHORT', 'u16', False),
    'FIXP_DBL': ('LONG', 'FixpDbl', False),
    'INT': ('INT', 'i32', False),
}


def rust_name(c):
    """Mechanical SCREAMING_SNAKE_CASE name of a C table."""
    if '_' in c:
        return c.upper()
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    s = re.sub(r'([A-Za-z])(\d)', r'\1_\2', s)
    return s.upper()


def dump(symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def lines(items, per_line):
    return ''.join('    ' + ', '.join(items[i:i + per_line]) + ',\n'
                   for i in range(0, len(items), per_line))


def table_item(name, ctype, vals):
    dtype, rtype, pairs = TYPES[ctype]
    rname = rust_name(name)
    cmd = f'scripts/dump_table.py {SRC} {name} {dtype}'
    if pairs:
        assert len(vals) % 2 == 0
        items = [f'spk({vals[i]}, {vals[i + 1]})' for i in range(0, len(vals), 2)]
        body = lines(items, 4)
        n = len(items)
        how = f'`{cmd}`, the (re, im) pairs wrapped with `spk()`'
    elif dtype == 'USHORT':
        body = lines([f'0x{v:04X}' for v in vals], 8)
        n = len(vals)
        how = f'`{cmd}`'
    elif dtype == 'LONG':
        items = [f'0x{v:08X}' if v >= 0 else str(v) for v in vals]
        body = lines(items, 6)
        n = len(vals)
        how = f'`{cmd}`'
    else:
        body = lines([str(v) for v in vals], 10 if dtype == 'SHORT' else 12)
        n = len(vals)
        how = f'`{cmd}`'
    return (f'/// `{name}`\n///\n/// Generated with {how}.\npub static {rname}: [{rtype}; {n}] = [\n'
            f'{body}];\n')


def rbd_enum(hdr):
    m = re.search(r'typedef enum \{(.*?)\} rbd_id_t;', hdr, re.S)
    text = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    names = [n.strip() for n in text.split(',') if n.strip()]
    for n in names:
        assert re.fullmatch(r'[A-Za-z_]\w*', n), n
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()
    src = open(os.path.join(dump_table.CDIR, SRC)).read()
    hdr = open(os.path.join(dump_table.CDIR, HDR)).read()

    tables = re.findall(r'^const (FIXP_\w+|USHORT|INT) (\w+)\[[^\]]*\]\s*=', src, re.M)
    lists = re.findall(r'^static const rbd_id_t (\w+)\[\]\s*=', src, re.M)
    names = rbd_enum(hdr)

    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        tvals = list(ex.map(lambda t: dump(t[1], TYPES[t[0]][0]), tables))
        lvals = list(ex.map(lambda n: dump(n, 'INT'), lists))

    out = HEADER + '''
//! The constant tables of `FDK_tools_rom.cpp`.

use super::{FixpPft, FixpQtw};
use crate::archdef::{FixpStb, FixpStp, FixpWtp};
use crate::common_fix::{FixpDbl, FixpSpk};

const fn spk(re: i16, im: i16) -> FixpSpk {
    FixpSpk { re, im }
}
'''
    for (ctype, name), vals in zip(tables, tvals):
        out += '\n' + table_item(name, ctype, vals)
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)

    out = HEADER + '''
//! `rbd_id_t` and the bitstream element lists of `FDK_tools_rom.cpp`.

/// `rbd_id_t`: raw data block list items. The variants keep the C++ names.
#[repr(i32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum RbdIdT {
'''
    for i, n in enumerate(names):
        out += f'    {n} = {i},\n'
    out += '}\n\nuse RbdIdT::*;\n'
    for name, vals in zip(lists, lvals):
        items = [names[v] for v in vals]
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} INT`.\n'
                f'pub static {rust_name(name)}: [RbdIdT; {len(items)}] = [\n'
                f'{lines(items, 4)}];\n')
    open(os.path.join(HERE, 'element_lists.rs'), 'w').write(out)
    print(f'{len(tables)} tables, {len(lists)} element lists, {len(names)} rbd_id_t values')


if __name__ == '__main__':
    main()
