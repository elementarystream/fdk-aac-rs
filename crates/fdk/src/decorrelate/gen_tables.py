#!/usr/bin/env python3
"""Generate crates/fdk/src/decorrelate/tables.rs from the C++ reference.

Every table of libFDK/src/FDK_decorrelate.cpp is dumped with scripts/dump_table.py, which compiles
the C++ source on arm64 and x86_64 and fails if the two give different values. Nothing is
retyped: the values come from the dump; the shapes below are only used to format the values and
are checked against the number of dumped values.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/fdk/src/decorrelate/gen_tables.py [-j JOBS]
"""
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402  (for the location of the C++ sources)

SRC = 'libFDK/src/FDK_decorrelate.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libFDK/src/FDK_decorrelate.cpp.
//
// GENERATED by `python3 crates/fdk/src/decorrelate/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.
'''

# C element type -> (dump type, Rust element type)
TYPES = {
    'UCHAR': ('UCHAR', 'u8'),
    'SCHAR': ('SCHAR', 'i8'),
    'REVBAND_FILT_TYPE': ('INT', 'RevbandFiltType'),
    'FIXP_DECORR': ('SHORT', 'FixpDecorr'),
    'FIXP_STP': ('SHORT', 'FixpStp'),  # (re, im) pairs
}

# name -> shape (in elements of the C type)
SHAPES = {
    'REV_bandOffset_MPS_HQ': [3, 4],
    'REV_bandOffset_PS_HQ': [4],
    'REV_bandOffset_PS_LP': [4],
    'REV_bandOffset_LD': [3, 4],
    'REV_delay_MPS': [4],
    'REV_filterOrder_MPS': [4],
    'REV_delay_PS_HQ': [4],
    'REV_delay_PS_LP': [4],
    'REV_filterOrder_PS': [4],
    'REV_delay_USAC': [4],
    'REV_filterOrder_USAC': [4],
    'REV_filtType_MPS': [4],
    'REV_filtType_PS': [4],
    'stateBufferOffsetInit': [3],
    'REV_filtType_LD': [4],
    'kernels_20_to_71_PS': [72],
    'kernels_20_to_71_offset_PS': [21],
    'kernels_28_to_71': [72],
    'kernels_28_to_71_offset': [29],
    'kernels_23_to_64': [65],
    'kernels_23_to_64_offset': [24],
    'DecorrPsCoeffsCplx': [30, 4],
    'DecorrNumeratorReal0_USAC': [1, 11],
    'DecorrNumeratorReal1_USAC': [1, 9],
    'DecorrNumeratorReal2_USAC': [1, 4],
    'DecorrNumeratorReal3_USAC': [1, 3],
    'DecorrNumeratorReal1_LD': [4, 16],
    'DecorrNumeratorReal2_LD': [4, 7],
    'DecorrNumeratorReal3_LD': [4, 4],
}


def rust_name(c):
    """Mechanical SCREAMING_SNAKE_CASE name of a C table."""
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', c)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.upper()


def dump(symbol, elemtype):
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), SRC, symbol, elemtype]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {symbol}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    return [int(v) for v in re.findall(r'-?\d+', body)]


def literal(items, shape, indent):
    if len(shape) == 1:
        lines = [', '.join(items[i:i + 8]) for i in range(0, len(items), 8)]
        if len(lines) == 1:
            return '[' + lines[0] + ']'
        pad = ' ' * (indent + 4)
        return '[\n' + ''.join(f'{pad}{l},\n' for l in lines) + ' ' * indent + ']'
    step = len(items) // shape[0]
    pad = ' ' * (indent + 4)
    inner = [literal(items[i * step:(i + 1) * step], shape[1:], indent + 4)
             for i in range(shape[0])]
    return '[\n' + ''.join(f'{pad}{x},\n' for x in inner) + ' ' * indent + ']'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()
    src = open(os.path.join(dump_table.CDIR, SRC)).read()
    tables = re.findall(r'^(?:static )?const\s+(\w+)\s+(\w+)\s*\[', src, re.M)
    tables = [(t, n) for t, n in tables if t in TYPES]
    assert sorted(n for _, n in tables) == sorted(SHAPES), 'table list changed'

    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        vals = list(ex.map(lambda t: dump(t[1], TYPES[t[0]][0]), tables))

    out = HEADER + '''
//! The tables of `FDK_decorrelate.cpp`.

use super::{FixpDecorr, RevbandFiltType};
use crate::archdef::FixpStp;
use crate::common_fix::FixpSpk;

const fn spk(re: i16, im: i16) -> FixpSpk {
    FixpSpk { re, im }
}
'''
    for (ctype, name), v in zip(tables, vals):
        shape = SHAPES[name]
        dtype, rtype = TYPES[ctype]
        if ctype == 'FIXP_STP':
            assert len(v) % 2 == 0
            items = [f'spk({v[i]}, {v[i + 1]})' for i in range(0, len(v), 2)]
        else:
            items = [str(x) for x in v]
        n = 1
        for d in shape:
            n *= d
        assert len(items) == n, (name, len(items), shape)
        ty = rtype
        for d in reversed(shape):
            ty = f'[{ty}; {d}]'
        out += (f'\n/// `{name}`\n///\n/// Generated with `scripts/dump_table.py {SRC} {name} {dtype}`.\n'
                f'#[rustfmt::skip]\npub static {rust_name(name)}: {ty} = {literal(items, shape, 0)};\n')
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)
    print(f'{len(tables)} tables')


if __name__ == '__main__':
    main()
