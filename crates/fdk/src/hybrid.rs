/// `FDK_ANA_HYB_FILTER` (`HANDLE_FDK_ANA_HYB_FILTER` is `&mut FdkAnaHybFilter`). The LF and HF
/// memory is owned (see the [module documentation](self)); the buffers are offsets into it.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct FdkAnaHybFilter {
    /// `bufferLFReal`: LF real filter states (offsets into `p_lf_memory`)
    pub buffer_lf_real: [isize; 3],
    /// `bufferLFImag`: LF imag filter states (offsets into `p_lf_memory`)
    pub buffer_lf_imag: [isize; 3],
    /// `bufferHFReal`: HF real delay lines (offsets into `p_hf_memory`)
    pub buffer_hf_real: [isize; 13],
    /// `bufferHFImag`: HF imag delay lines (offsets into `p_hf_memory`)
    pub buffer_hf_imag: [isize; 13],

    /// `bufferLFpos`: position to write incoming data into the ring buffer
    pub buffer_lf_pos: i32,
    /// `bufferHFpos`: delay line position
    pub buffer_hf_pos: i32,
    /// `nrBands`: number of QMF bands
    pub nr_bands: i32,
    /// `cplxBands`: number of complex QMF bands
    pub cplx_bands: i32,
    /// `hfMode`: treatment of the HF bands (non-zero: the HF delay is compensated outside)
    pub hf_mode: u8,

    /// `pLFmemory`: LF states buffer (empty for `NULL`)
    pub p_lf_memory: Vec<FixpDbl>,
    /// `pHFmemory`: HF states buffer (empty for `NULL`)
    pub p_hf_memory: Vec<FixpDbl>,

    /// `LFmemorySize`: size of the LF states buffer in bytes
    pub lf_memory_size: u32,
    /// `HFmemorySize`: size of the HF states buffer in bytes
    pub hf_memory_size: u32,

    /// `pSetup`: the filter setup (`None` for `NULL`)
    pub p_setup: Option<&'static FdkHybridSetup>,
}

