//! Port of `FDK_hybrid.h` and `FDK_hybrid.cpp`: the hybrid analysis and synthesis filter banks
//! that split the lowest QMF bands further (MPEG Surround, parametric stereo).
//!
//! # Memory
//!
//! In C, `FDKhybridAnalysisOpen()` receives the LF and HF state memory from its caller and
//! `FDKhybridAnalysisInit()` distributes it: `bufferLFReal[k]` etc. are pointers into it. In
//! the port the analysis filter bank owns the memory ([`FdkAnaHybFilter::p_lf_memory`],
//! [`FdkAnaHybFilter::p_hf_memory`], moved in by [`fdk_hybrid_analysis_open`]) and the buffer
//! pointers are offsets into it. No other code of the library accesses that memory directly.
//!
//! # Variants
//!
//! The `.ii` files of the `aarch64` and `x86` builds differ only in the `SATURATE_LEFT_SHIFT`
//! macro (same values for the shift amounts 1 and 3 used here) and `FDK_ASSERT`; the values
//! differ through the primitives (`fMult` in `fourChannelFiltering`, the `cplxMultDiv2`
//! assembly of `aarch64` in `eightChannelFiltering`) and through `fft_8` (inlined into this
//! file in the reference; covered by the `cref` tests of [`fdk_hybrid_analysis_apply`], which
//! call the library's own code).
//!
//! # Undefined behavior
//!
//! The sums of the filters can overflow for full-scale input; both builds wrap (scalar and
//! vector `add`/`sub`), so the port uses `wrapping_*`.

