/// The slice of `len` values of `mem` at `off`; `None` outside of the buffer.
fn mem_at(mem: &[FixpDbl], off: isize, len: i32) -> Option<&[FixpDbl]> {
    if off < 0 || len < 0 {
        return None;
    }
    mem.get(off as usize..off as usize + len as usize)
}

fn mem_at_mut(mem: &mut [FixpDbl], off: isize, len: i32) -> Option<&mut [FixpDbl]> {
    if off < 0 || len < 0 {
        return None;
    }
    mem.get_mut(off as usize..off as usize + len as usize)
}

/// `FDKmemcpy(dst, src, n * sizeof(FIXP_DBL))` for `n >= 0`, limited to the ends of both.
///
/// Deviation: for a negative count the reference has no defined result; the port copies
/// nothing.
fn copy_n(dst: &mut [FixpDbl], src: &[FixpDbl], n: i32) {
    let n = (n.max(0) as usize).min(dst.len()).min(src.len());
    dst[..n].copy_from_slice(&src[..n]);
}

fn setup_of(mode: FdkHybridMode) -> Option<&'static FdkHybridSetup> {
    match mode {
        THREE_TO_TEN => Some(&SETUP_3_10),
        THREE_TO_TWELVE => Some(&SETUP_3_12),
        THREE_TO_SIXTEEN => Some(&SETUP_3_16),
        _ => None,
    }
}

/// `FDKhybridAnalysisOpen(hAnalysisHybFilter, pLFmemory, LFmemorySize, pHFmemory,
/// HFmemorySize)`: stores the state memory (moved into the filter bank; an empty vector is
/// `NULL`) and its sizes in bytes. Returns 0.
pub fn fdk_hybrid_analysis_open(
    h_analysis_hyb_filter: &mut FdkAnaHybFilter,
    p_lf_memory: Vec<FixpDbl>,
    lf_memory_size: u32,
    p_hf_memory: Vec<FixpDbl>,
    hf_memory_size: u32,
) -> i32 {
    let err = 0;

    // Save pointer to extern memory.
    h_analysis_hyb_filter.p_lf_memory = p_lf_memory;
    h_analysis_hyb_filter.lf_memory_size = lf_memory_size;

    h_analysis_hyb_filter.p_hf_memory = p_hf_memory;
    h_analysis_hyb_filter.hf_memory_size = hf_memory_size;

    err
}

/// `FDKhybridAnalysisInit(hAnalysisHybFilter, mode, qmfBands, cplxBands, initStatesFlag)`:
/// initializes and configures the analysis filter bank. Returns 0 on success, -1 for an
/// unknown mode, -2 or -3 if the LF or HF memory is too small.
pub fn fdk_hybrid_analysis_init(
    h_analysis_hyb_filter: &mut FdkAnaHybFilter,
    mode: FdkHybridMode,
    qmf_bands: i32,
    cplx_bands: i32,
    init_states_flag: i32,
) -> i32 {
    let h = h_analysis_hyb_filter;
    let Some(setup) = setup_of(mode) else {
        return -1;
    };
    let nr_qmf_bands = setup.nr_qmf_bands as i32;
    let proto_len = setup.proto_len as i32;
    let filter_delay = setup.filter_delay as i32;

    // Initialize handle.
    h.p_setup = Some(setup);
    if init_states_flag != 0 {
        h.buffer_lf_pos = proto_len - 1;
        h.buffer_hf_pos = 0;
    }
    h.nr_bands = qmf_bands;
    h.cplx_bands = cplx_bands;
    h.hf_mode = 0;

    // Check available memory.
    if (2 * nr_qmf_bands * proto_len) as u64 * 4 > h.lf_memory_size as u64 {
        return -2;
    }
    if h.hf_memory_size != 0 {
        // The C product is converted to size_t: a negative band count compares as huge.
        let n = filter_delay as i64
            * ((qmf_bands as i64 - nr_qmf_bands as i64)
                + (cplx_bands as i64 - nr_qmf_bands as i64))
            * 4;
        if n as u64 > h.hf_memory_size as u64 {
            return -3;
        }
    }

    // Distribute LF memory.
    let mut p_mem: isize = 0;
    for k in 0..nr_qmf_bands as usize {
        h.buffer_lf_real[k] = p_mem;
        p_mem += proto_len as isize;
        h.buffer_lf_imag[k] = p_mem;
        p_mem += proto_len as isize;
    }

    // Distribute HF memory.
    if h.hf_memory_size != 0 {
        let mut p_mem: isize = 0;
        for k in 0..filter_delay as usize {
            h.buffer_hf_real[k] = p_mem;
            p_mem += (qmf_bands - nr_qmf_bands) as isize;
            h.buffer_hf_imag[k] = p_mem;
            p_mem += (cplx_bands - nr_qmf_bands) as isize;
        }
    }

    if init_states_flag != 0 {
        // Clear LF buffer
        for k in 0..nr_qmf_bands as usize {
            if let Some(b) = mem_at_mut(&mut h.p_lf_memory, h.buffer_lf_real[k], proto_len) {
                b.fill(0);
            }
            if let Some(b) = mem_at_mut(&mut h.p_lf_memory, h.buffer_lf_imag[k], proto_len) {
                b.fill(0);
            }
        }

        if h.hf_memory_size != 0 && qmf_bands > nr_qmf_bands {
            // Clear HF buffer
            for k in 0..filter_delay as usize {
                if let Some(b) =
                    mem_at_mut(&mut h.p_hf_memory, h.buffer_hf_real[k], qmf_bands - nr_qmf_bands)
                {
                    b.fill(0);
                }
                if let Some(b) =
                    mem_at_mut(&mut h.p_hf_memory, h.buffer_hf_imag[k], cplx_bands - nr_qmf_bands)
                {
                    b.fill(0);
                }
            }
        }
    }

    0
}

/// `scaleValues(vector, len, scalingValue)` for a buffer of the filter bank; a negative length
/// does nothing (deviation).
fn scale_buffer(mem: &mut [FixpDbl], off: isize, len: i32, scaling_value: i32) {
    if let Some(b) = mem_at_mut(mem, off, len) {
        crate::scale::scale_values(b, scaling_value);
    }
}

/// `FDKhybridAnalysisScaleStates(hAnalysisHybFilter, scalingValue)`: scales the filter states.
/// `None` is a `NULL` handle (returns 1).
pub fn fdk_hybrid_analysis_scale_states(
    h_analysis_hyb_filter: Option<&mut FdkAnaHybFilter>,
    scaling_value: i32,
) -> i32 {
    let Some(h) = h_analysis_hyb_filter else {
        return 1; // invalid handle
    };
    let Some(setup) = h.p_setup else {
        return 0;
    };
    let nr_qmf_bands = setup.nr_qmf_bands as i32;
    let proto_len = setup.proto_len as i32;

    // Scale LF buffer
    for k in 0..nr_qmf_bands as usize {
        scale_buffer(&mut h.p_lf_memory, h.buffer_lf_real[k], proto_len, scaling_value);
        scale_buffer(&mut h.p_lf_memory, h.buffer_lf_imag[k], proto_len, scaling_value);
    }
    if h.nr_bands > nr_qmf_bands {
        // Scale HF buffer
        for k in 0..setup.filter_delay as usize {
            let (re, im) = (h.buffer_hf_real[k], h.buffer_hf_imag[k]);
            scale_buffer(&mut h.p_hf_memory, re, h.nr_bands - nr_qmf_bands, scaling_value);
            scale_buffer(&mut h.p_hf_memory, im, h.cplx_bands - nr_qmf_bands, scaling_value);
        }
    }
    0
}

/// `FDKhybridAnalysisApply(hAnalysisHybFilter, pQmfReal, pQmfImag, pHybridReal, pHybridImag)`:
/// filters one QMF slot. Returns 0 on success.
///
/// Deviation: without a setup the reference has no defined result; the port returns 0 without
/// output.
pub fn fdk_hybrid_analysis_apply(
    h_analysis_hyb_filter: &mut FdkAnaHybFilter,
    p_qmf_real: &[FixpDbl],
    p_qmf_imag: &[FixpDbl],
    p_hybrid_real: &mut [FixpDbl],
    p_hybrid_imag: &mut [FixpDbl],
) -> i32 {
    let h = h_analysis_hyb_filter;
    let Some(setup) = h.p_setup else {
        return 0;
    };
    let mut hyb_offset = 0usize;
    let mut err = 0;
    // number of QMF bands to be converted to hybrid
    let nr_qmf_bands_lf = setup.nr_qmf_bands as usize;
    let proto_len = setup.proto_len as i32;

    let writ_index = h.buffer_lf_pos;
    let mut read_index = h.buffer_lf_pos + 1;

    if read_index >= proto_len {
        read_index = 0;
    }
    let p_buffer_lf_read_idx = &setup.p_read_idx_table[read_index as usize..];

    // LF buffer.
    for k in 0..nr_qmf_bands_lf {
        let (off_re, off_im) = (h.buffer_lf_real[k], h.buffer_lf_imag[k]);
        let lf = &mut h.p_lf_memory;
        if mem_at(lf, off_re, proto_len).is_none() || mem_at(lf, off_im, proto_len).is_none() {
            // Deviation: a too small LF buffer (no defined result in C) is skipped.
            continue;
        }
        // New input sample.
        lf[off_re as usize + writ_index as usize] = p_qmf_real[k];
        lf[off_im as usize + writ_index as usize] = p_qmf_imag[k];

        // Perform hybrid filtering.
        let buf_re = &lf[off_re as usize..off_re as usize + proto_len as usize];
        let buf_im = &lf[off_im as usize..off_im as usize + proto_len as usize];
        err |= k_channel_filtering(
            buf_re,
            buf_im,
            p_buffer_lf_read_idx,
            &mut p_hybrid_real[hyb_offset..],
            &mut p_hybrid_imag[hyb_offset..],
            setup.k_hybrid[k],
        );

        hyb_offset += setup.n_hyb_bands[k] as usize;
    }

    h.buffer_lf_pos = read_index; // Index where to write next input sample.

    if h.nr_bands > nr_qmf_bands_lf as i32 {
        let n_re = h.nr_bands - nr_qmf_bands_lf as i32;
        let n_im = h.cplx_bands - nr_qmf_bands_lf as i32;
        // HF buffer.
        if h.hf_mode != 0 {
            // HF delay compensation was applied outside.
            copy_n(&mut p_hybrid_real[hyb_offset..], &p_qmf_real[nr_qmf_bands_lf..], n_re);
            copy_n(&mut p_hybrid_imag[hyb_offset..], &p_qmf_imag[nr_qmf_bands_lf..], n_im);
        } else {
            fdk_assert!(h.hf_memory_size != 0);
            // HF delay compensation, filterlength/2.
            let pos = h.buffer_hf_pos.clamp(0, 12) as usize;
            let (off_re, off_im) = (h.buffer_hf_real[pos], h.buffer_hf_imag[pos]);
            if let Some(b) = mem_at(&h.p_hf_memory, off_re, n_re) {
                copy_n(&mut p_hybrid_real[hyb_offset..], b, n_re);
            }
            if let Some(b) = mem_at(&h.p_hf_memory, off_im, n_im) {
                copy_n(&mut p_hybrid_imag[hyb_offset..], b, n_im);
            }

            if let Some(b) = mem_at_mut(&mut h.p_hf_memory, off_re, n_re) {
                copy_n(b, &p_qmf_real[nr_qmf_bands_lf..], n_re);
            }
            if let Some(b) = mem_at_mut(&mut h.p_hf_memory, off_im, n_im) {
                copy_n(b, &p_qmf_imag[nr_qmf_bands_lf..], n_im);
            }

            h.buffer_hf_pos += 1;
            if h.buffer_hf_pos >= setup.filter_delay as i32 {
                h.buffer_hf_pos = 0;
            }
        }
    } // process HF part

    err
}

/// `FDKhybridAnalysisClose(hAnalysisHybFilter)`: releases the state memory (`None` is a `NULL`
/// handle). Returns 0.
pub fn fdk_hybrid_analysis_close(h_analysis_hyb_filter: Option<&mut FdkAnaHybFilter>) -> i32 {
    if let Some(h) = h_analysis_hyb_filter {
        h.p_lf_memory = Vec::new();
        h.p_hf_memory = Vec::new();
        h.lf_memory_size = 0;
        h.hf_memory_size = 0;
    }
    0
}

/// `FDKhybridSynthesisInit(hSynthesisHybFilter, mode, qmfBands, cplxBands)`: returns 0 on
/// success, -1 for an unknown mode.
pub fn fdk_hybrid_synthesis_init(
    h_synthesis_hyb_filter: &mut FdkSynHybFilter,
    mode: FdkHybridMode,
    qmf_bands: i32,
    cplx_bands: i32,
) -> i32 {
    let Some(setup) = setup_of(mode) else {
        return -1;
    };

    h_synthesis_hyb_filter.p_setup = Some(setup);
    h_synthesis_hyb_filter.nr_bands = qmf_bands;
    h_synthesis_hyb_filter.cplx_bands = cplx_bands;

    0
}

/// `FDKhybridSynthesisApply(hSynthesisHybFilter, pHybridReal, pHybridImag, pQmfReal,
/// pQmfImag)`: combines the hybrid bands of one slot into QMF bands.
///
/// Deviation: without a setup the reference has no defined result; the port does nothing.
pub fn fdk_hybrid_synthesis_apply(
    h_synthesis_hyb_filter: &FdkSynHybFilter,
    p_hybrid_real: &[FixpDbl],
    p_hybrid_imag: &[FixpDbl],
    p_qmf_real: &mut [FixpDbl],
    p_qmf_imag: &mut [FixpDbl],
) {
    let Some(setup) = h_synthesis_hyb_filter.p_setup else {
        return;
    };
    let mut hyb_offset = 0usize;
    let nr_qmf_bands_lf = setup.nr_qmf_bands as usize;

    // LF buffer.
    for k in 0..nr_qmf_bands_lf {
        let n_hyb_bands = setup.n_hyb_bands[k] as usize;
        let scale = setup.syn_hyb_scale[k] as i32;

        let mut accu1: FixpDbl = 0;
        let mut accu2: FixpDbl = 0;

        // Perform hybrid filtering.
        for n in 0..n_hyb_bands {
            accu1 = accu1.wrapping_add(p_hybrid_real[hyb_offset + n] >> scale);
            accu2 = accu2.wrapping_add(p_hybrid_imag[hyb_offset + n] >> scale);
        }
        p_qmf_real[k] = saturate_left_shift(accu1, scale, DFRACT_BITS);
        p_qmf_imag[k] = saturate_left_shift(accu2, scale, DFRACT_BITS);

        hyb_offset += n_hyb_bands;
    }

    if h_synthesis_hyb_filter.nr_bands > nr_qmf_bands_lf as i32 {
        // HF buffer.
        copy_n(
            &mut p_qmf_real[nr_qmf_bands_lf..],
            &p_hybrid_real[hyb_offset..],
            h_synthesis_hyb_filter.nr_bands - nr_qmf_bands_lf as i32,
        );
        copy_n(
            &mut p_qmf_imag[nr_qmf_bands_lf..],
            &p_hybrid_imag[hyb_offset..],
            h_synthesis_hyb_filter.cplx_bands - nr_qmf_bands_lf as i32,
        );
    }
}

/// `dualChannelFiltering()`
fn dual_channel_filtering(
    p_qmf_real: &[FixpDbl],
    p_qmf_imag: &[FixpDbl],
    p_read_idx: &[i32],
    m_hybrid_real: &mut [FixpDbl],
    m_hybrid_imag: &mut [FixpDbl],
    invert: usize,
) {
    let re = |i: usize| p_qmf_real[p_read_idx[i] as usize];
    let im = |i: usize| p_qmf_imag[p_read_idx[i] as usize];

    let f0 = HYB_FILTER_COEF2[0]; // corresponds to p1 and p11
    let f1 = HYB_FILTER_COEF2[1]; // corresponds to p3 and p9
    let f2 = HYB_FILTER_COEF2[2]; // corresponds to p5 and p7

    // symmetric filter coefficients
    let mut r1 = f_mult_div2(f0, re(1)).wrapping_add(f_mult_div2(f0, re(11)));
    let mut i1 = f_mult_div2(f0, im(1)).wrapping_add(f_mult_div2(f0, im(11)));
    r1 = r1.wrapping_add(f_mult_div2(f1, re(3)).wrapping_add(f_mult_div2(f1, re(9))));
    i1 = i1.wrapping_add(f_mult_div2(f1, im(3)).wrapping_add(f_mult_div2(f1, im(9))));
    r1 = r1.wrapping_add(f_mult_div2(f2, re(5)).wrapping_add(f_mult_div2(f2, re(7))));
    i1 = i1.wrapping_add(f_mult_div2(f2, im(5)).wrapping_add(f_mult_div2(f2, im(7))));

    let r6 = re(6) >> 2;
    let i6 = im(6) >> 2;

    fdk_assert!(invert == 0 || invert == 1);
    m_hybrid_real[invert] = saturate_left_shift(r6.wrapping_add(r1), 1, DFRACT_BITS);
    m_hybrid_imag[invert] = saturate_left_shift(i6.wrapping_add(i1), 1, DFRACT_BITS);

    m_hybrid_real[1 - invert] = saturate_left_shift(r6.wrapping_sub(r1), 1, DFRACT_BITS);
    m_hybrid_imag[1 - invert] = saturate_left_shift(i6.wrapping_sub(i1), 1, DFRACT_BITS);
}

/// `fourChannelFiltering()`
fn four_channel_filtering(
    p_qmf_real: &[FixpDbl],
    p_qmf_imag: &[FixpDbl],
    p_read_idx: &[i32],
    m_hybrid_real: &mut [FixpDbl],
    m_hybrid_imag: &mut [FixpDbl],
    _invert: usize,
) {
    let p = &HYB_FILTER_COEF4;
    let re = |i: usize| p_qmf_real[p_read_idx[i] as usize];
    let im = |i: usize| p_qmf_imag[p_read_idx[i] as usize];

    // pre twiddeling with pre-twiddling coefficients c[n], multiplication with filter
    // coefficients p[n]: fMult(p[k], fMultSub(fMultDiv2(cr[n], re[n]), ci[n], im[n])) for the
    // real part, fMult(p[k], fMultAdd(fMultDiv2(ci[n], re[n]), cr[n], im[n])) for the
    // imaginary part.
    // hint: (a + ib)*(c + id) = (a*c - b*d) + i(a*d + b*c)
    let tr = |k: usize, n: usize| f_mult(p[k], f_mult_sub(f_mult_div2(CR[n], re(n)), CI[n], im(n)));
    let ti = |k: usize, n: usize| f_mult(p[k], f_mult_add(f_mult_div2(CI[n], re(n)), CR[n], im(n)));

    let mut fft = [0 as FixpDbl; 8];
    // write to fft coefficient n'
    fft[0] = tr(10, 2).wrapping_add(tr(6, 6)).wrapping_add(tr(2, 10));
    fft[1] = ti(10, 2).wrapping_add(ti(6, 6)).wrapping_add(ti(2, 10));

    // twiddle dee dum
    fft[2] = tr(9, 3).wrapping_add(tr(5, 7)).wrapping_add(tr(1, 11));
    fft[3] = ti(9, 3).wrapping_add(ti(5, 7)).wrapping_add(ti(1, 11));

    // twiddle dee dee
    fft[4] = tr(12, 0).wrapping_add(tr(8, 4)).wrapping_add(tr(4, 8)).wrapping_add(tr(0, 12));
    fft[5] = ti(12, 0).wrapping_add(ti(8, 4)).wrapping_add(ti(4, 8)).wrapping_add(ti(0, 12));

    fft[6] = tr(11, 1).wrapping_add(tr(7, 5)).wrapping_add(tr(3, 9));
    fft[7] = ti(11, 1).wrapping_add(ti(7, 5)).wrapping_add(ti(3, 9));

    let r = |n: usize| fft[2 * n];
    let i = |n: usize| fft[2 * n + 1];

    // fft modulation: fast manual fft modulation for a fft of length M=4
    // fft_4{x[n]} = x[0]*exp(-i*2*pi/4*m*0) + x[1]*exp(-i*2*pi/4*m*1) +
    //               x[2]*exp(-i*2*pi/4*m*2) + x[3]*exp(-i*2*pi/4*m*3)

    // fft bin m=0: X[0, n] = x[0] + x[1] + x[2] + x[3]
    m_hybrid_real[0] = r(0).wrapping_add(r(1)).wrapping_add(r(2)).wrapping_add(r(3));
    m_hybrid_imag[0] = i(0).wrapping_add(i(1)).wrapping_add(i(2)).wrapping_add(i(3));

    // fft bin m=1: X[1, n] = x[0] - i*x[1] - x[2] + i*x[3]
    m_hybrid_real[1] = r(0).wrapping_add(i(1)).wrapping_sub(r(2)).wrapping_sub(i(3));
    m_hybrid_imag[1] = i(0).wrapping_sub(r(1)).wrapping_sub(i(2)).wrapping_add(r(3));

    // fft bin m=2: X[2, n] = x[0] - x[1] + x[2] - x[3]
    m_hybrid_real[2] = r(0).wrapping_sub(r(1)).wrapping_add(r(2)).wrapping_sub(r(3));
    m_hybrid_imag[2] = i(0).wrapping_sub(i(1)).wrapping_add(i(2)).wrapping_sub(i(3));

    // fft bin m=3: X[3, n] = x[0] + j*x[1] - x[2] - j*x[3]
    m_hybrid_real[3] = r(0).wrapping_sub(i(1)).wrapping_sub(r(2)).wrapping_add(i(3));
    m_hybrid_imag[3] = i(0).wrapping_add(r(1)).wrapping_sub(i(2)).wrapping_sub(r(3));
}

/// `eightChannelFiltering()`
fn eight_channel_filtering(
    p_qmf_real: &[FixpDbl],
    p_qmf_imag: &[FixpDbl],
    p_read_idx: &[i32],
    m_hybrid_real: &mut [FixpDbl],
    m_hybrid_imag: &mut [FixpDbl],
    invert: usize,
) {
    let p = &HYB_FILTER_COEF8;
    let re = |i: usize| p_qmf_real[p_read_idx[i] as usize];
    let im = |i: usize| p_qmf_imag[p_read_idx[i] as usize];
    let cmd2 = |n: usize, k: usize| cplx_mult_div2(re(n), im(n), p[k].re, p[k].im);

    let mut pfft = [0 as FixpDbl; 16];

    // pre twiddeling
    pfft[0] = re(6) >> (3 + 1); // fMultDiv2(p[0].v.re, pQmfReal[pReadIdx[6]]);
    pfft[1] = im(6) >> (3 + 1); // fMultDiv2(p[0].v.re, pQmfImag[pReadIdx[6]]);

    let (accu1, accu2) = cmd2(7, 1);
    pfft[2] = accu1;
    pfft[3] = accu2;

    let (accu1, accu2) = cmd2(0, 2);
    let (accu3, accu4) = cmd2(8, 3);
    pfft[4] = accu1.wrapping_add(accu3);
    pfft[5] = accu2.wrapping_add(accu4);

    let (accu1, accu2) = cmd2(1, 4);
    let (accu3, accu4) = cmd2(9, 5);
    pfft[6] = accu1.wrapping_add(accu3);
    pfft[7] = accu2.wrapping_add(accu4);

    pfft[8] = f_mult_div2(im(10), p[7].im).wrapping_sub(f_mult_div2(im(2), p[6].im));
    pfft[9] = f_mult_div2(re(2), p[6].im).wrapping_sub(f_mult_div2(re(10), p[7].im));

    let (accu1, accu2) = cmd2(3, 8);
    let (accu3, accu4) = cmd2(11, 9);
    pfft[10] = accu1.wrapping_add(accu3);
    pfft[11] = accu2.wrapping_add(accu4);

    let (accu1, accu2) = cmd2(4, 10);
    let (accu3, accu4) = cmd2(12, 11);
    pfft[12] = accu1.wrapping_add(accu3);
    pfft[13] = accu2.wrapping_add(accu4);

    let (accu1, accu2) = cmd2(5, 12);
    pfft[14] = accu1;
    pfft[15] = accu2;

    // fft modulation
    fft_8(&mut pfft);
    let sc = 1 + 2;

    if invert != 0 {
        m_hybrid_real[0] = pfft[14] << sc;
        m_hybrid_imag[0] = pfft[15] << sc;
        m_hybrid_real[1] = pfft[0] << sc;
        m_hybrid_imag[1] = pfft[1] << sc;

        m_hybrid_real[2] = pfft[12] << sc;
        m_hybrid_imag[2] = pfft[13] << sc;
        m_hybrid_real[3] = pfft[2] << sc;
        m_hybrid_imag[3] = pfft[3] << sc;

        m_hybrid_real[4] = saturate_left_shift(pfft[4].wrapping_add(pfft[10]), sc, DFRACT_BITS);
        m_hybrid_imag[4] = saturate_left_shift(pfft[5].wrapping_add(pfft[11]), sc, DFRACT_BITS);

        m_hybrid_real[5] = saturate_left_shift(pfft[6].wrapping_add(pfft[8]), sc, DFRACT_BITS);
        m_hybrid_imag[5] = saturate_left_shift(pfft[7].wrapping_add(pfft[9]), sc, DFRACT_BITS);
    } else {
        for k in 0..8 {
            m_hybrid_real[k] = pfft[2 * k] << sc;
            m_hybrid_imag[k] = pfft[2 * k + 1] << sc;
        }
    }
}

/// `kChannelFiltering()`: returns 0, or -1 for an unknown configuration.
fn k_channel_filtering(
    p_qmf_real: &[FixpDbl],
    p_qmf_imag: &[FixpDbl],
    p_read_idx: &[i32],
    m_hybrid_real: &mut [FixpDbl],
    m_hybrid_imag: &mut [FixpDbl],
    hybrid_config: i8,
) -> i32 {
    let invert = if hybrid_config < 0 { 1 } else { 0 };
    match hybrid_config {
        2 | -2 => dual_channel_filtering(
            p_qmf_real,
            p_qmf_imag,
            p_read_idx,
            m_hybrid_real,
            m_hybrid_imag,
            invert,
        ),
        4 | -4 => four_channel_filtering(
            p_qmf_real,
            p_qmf_imag,
            p_read_idx,
            m_hybrid_real,
            m_hybrid_imag,
            invert,
        ),
        8 | -8 => eight_channel_filtering(
            p_qmf_real,
            p_qmf_imag,
            p_read_idx,
            m_hybrid_real,
            m_hybrid_imag,
            invert,
        ),
        _ => return -1,
    }
    0
}
