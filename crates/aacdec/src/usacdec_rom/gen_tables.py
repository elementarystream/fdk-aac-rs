#!/usr/bin/env python3
"""Generate crates/aacdec/src/usacdec_rom/tables.rs from the C++ reference.

Every table of libAACdec/src/usacdec_rom.cpp is a table of scalars. The list of tables (name,
element type, rank) is taken from the definitions in usacdec_rom.cpp; each table is dumped with
scripts/dump_table.py, which compiles the source for arm64 and x86_64 and fails if they give
different values. The dimensions of the multi-dimensional tables are printed by a small program
compiled against the source on both architectures. The helpers are those of
crates/aacdec/src/aac_rom/gen_tables.py.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacdec/src/usacdec_rom/gen_tables.py [-j JOBS]
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'aac_rom'))
sys.dont_write_bytecode = True
import gen_tables as g  # noqa: E402  (crates/aacdec/src/aac_rom/gen_tables.py)

SRC = 'libAACdec/src/usacdec_rom.cpp'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-j', type=int, default=3)
    a = ap.parse_args()

    tables, shp, vals = g.scalar_tables(SRC, a.j)
    out = g.LICENSE + f'''//
// Ported from {SRC}.
//
// GENERATED by `python3 crates/aacdec/src/usacdec_rom/gen_tables.py`; do not edit. Every table
// is dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! The constant tables of `usacdec_rom.cpp`.

use fdk_aac_rs_fdk::archdef::FixpWtb;
use fdk_aac_rs_fdk::common_fix::FixpSgl;
use fdk_aac_rs_fdk::lpc::FixpLpc;
'''
    for (static, ctype, name, rank, _), v in zip(tables, vals):
        out += '\n' + g.table_item(SRC, ctype, name, shp[name], v, None)
    open(os.path.join(HERE, 'tables.rs'), 'w').write(out)
    print(f'{len(tables)} tables')


if __name__ == '__main__':
    main()
