#!/usr/bin/env python3
"""Generate the function-local tables of the AAC decoder glue from the C++ reference.

Writes
  crates/aacdec/src/aacdecoder/tables.rs   map_sbrRatio_2_nAnaBands of CAacDecoder_Init()
  crates/aacdec/src/aacdec_drc/tables.rs   b[], a[] of applyDrcLevelNormalization()
  crates/cref/shim/aacdec_tables_glue.cpp  the shim of the table test
                                           (crates/cref/tests/aacdec/tables_glue.rs)

Nothing is retyped. Function-local tables cannot be named from outside of their function: their
declaration is extracted from the C++ source text, renamed to `<function>_<name>_fnlocal`, made
`static const` and compiled at file scope after the source file (scripts/dump_table.py --prelude),
for arm64 and x86_64; dump_table.py fails if the architectures differ. The shim compiles the same
declarations with the reference headers, so that the test compares every element on both
variants.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/aacdec/src/aacdecoder/gen_tables.py
"""
import os
import re
import subprocess
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.dirname(HERE)
REPO = os.path.abspath(os.path.join(SRC_DIR, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
sys.dont_write_bytecode = True  # no __pycache__ in scripts/
import dump_table  # noqa: E402

GEN = 'python3 crates/aacdec/src/aacdecoder/gen_tables.py'

# (source, function, C name, C element type, dump type, Rust name, Rust element type, module,
#  doc)
TABLES = [
    ('libAACdec/src/aacdecoder.cpp', 'CAacDecoder_Init', 'map_sbrRatio_2_nAnaBands', 'UCHAR',
     'UCHAR', 'MAP_SBR_RATIO_2_N_ANA_BANDS', 'u8', 'aacdecoder',
     'the number of QMF analysis bands per USAC `sbrRatioIndex - 1`'),
    ('libAACdec/src/aacdec_drc.cpp', 'applyDrcLevelNormalization', 'b', 'FIXP_SGL', 'SHORT',
     'SMOOTH_B', 'FixpSgl', 'aacdec_drc', '`b` of the gain smoothing filter (`[b,a] = butter(1, 0.01)`)'),
    ('libAACdec/src/aacdec_drc.cpp', 'applyDrcLevelNormalization', 'a', 'FIXP_SGL', 'SHORT',
     'SMOOTH_A', 'FixpSgl', 'aacdec_drc', '`a` of the gain smoothing filter'),
]


def function_body(text, func):
    """The text of the definition of `func` (from its name to the end of the source)."""
    m = re.search(r'\b' + re.escape(func) + r'\s*\([^;{]*\)\s*\{', text)
    if not m:
        sys.exit(f'{func} not found')
    return text[m.start():]


def fnlocal_decl(src, func, name):
    """The declaration of the function-local table `name` of `func` in `src`, renamed to
    `<func>_<name>_fnlocal` and made `static const`."""
    text = function_body(open(os.path.join(dump_table.CDIR, src)).read(), func)
    pat = (r'(?:static\s+)?const\s+([A-Za-z_][A-Za-z_0-9]*)\s+' + re.escape(name) +
           r'\s*((?:\[[^\]]*\])+)\s*=\s*(\{.*?\});')
    m = re.search(pat, text, re.S)
    if not m:
        sys.exit(f'{name} not found in {func} of {src}')
    init = re.sub(r'\s+', ' ', re.sub(r'/\*.*?\*/', '', m.group(3), flags=re.S))
    return f'static const {m.group(1)} {func}_{name}_fnlocal{m.group(2)} = {init};'


def dump(src, func, name, dtype):
    decl = fnlocal_decl(src, func, name)
    sym = f'{func}_{name}_fnlocal'
    cmd = [sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py'), src, sym, dtype,
           '--prelude', decl]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode != 0:
        sys.exit(f'dump_table.py failed for {name}:\n{r.stderr}')
    body = r.stdout.split('=', 1)[1]
    vals = [int(v) for v in re.findall(r'-?\d+', body)]
    return decl, vals, f"scripts/dump_table.py {src} {sym} {dtype} --prelude '{decl}'"


def main():
    results = [dump(t[0], t[1], t[2], t[4]) for t in TABLES]

    for module in ('aacdecoder', 'aacdec_drc'):
        rows = [(t, r) for t, r in zip(TABLES, results) if t[7] == module]
        src = rows[0][0][0]
        out = [
            '// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library'
            ' for Android.',
            '// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.',
            '//',
            f'// Ported from {src}.',
            '//',
            f'// GENERATED by `{GEN}`; do not edit.',
            '',
            f'//! The function-local tables of `{os.path.basename(src)}`.',
            '',
        ]
        if any(t[6] == 'FixpSgl' for t, _ in rows):
            out += ['use fdk_aac_rs_fdk::common_fix::FixpSgl;', '']
        for t, (decl, vals, cmd) in rows:
            doc = f'`{t[2]}` of `{t[1]}()` (a function-local table): {t[8]}.'
            out += ['/// ' + l for l in textwrap.wrap(doc, 96)]
            out += ['///',
                    '/// Dumped with',
                    f'/// `{cmd}`.',
                    f'pub static {t[5]}: [{t[6]}; {len(vals)}] = [{", ".join(map(str, vals))}];',
                    '']
        path = os.path.join(SRC_DIR, module, 'tables.rs')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write('\n'.join(out).rstrip('\n') + '\n')
        print(f'wrote {os.path.relpath(path, REPO)}')

    shim = [
        f'// GENERATED by `{GEN}`; do not edit.',
        '//',
        '// Shim of the table test of the function-local tables of the AAC decoder glue',
        '// (tests/aacdec/tables_glue.rs): the declarations of the C++ functions, renamed and made',
        '// `static const` at file scope, compiled with the reference headers. Writes every element',
        '// in the order of the generator.',
        '',
        '#include "cref_common.h"',
        '#include "common_fix.h"',
        '',
        'namespace tbl {',
    ]
    shim += [decl for decl, _, _ in results]
    shim += ['}  // namespace tbl', '', 'extern "C" {']
    for t, (decl, vals, _) in zip(TABLES, results):
        sym = f'{t[1]}_{t[2]}_fnlocal'
        shim += [
            f'INT cref_tables_glue_{t[5].lower()}(INT *out) {{',
            f'  const {t[4]} *p = (const {t[4]} *)(const void *)tbl::{sym};',
            f'  INT n = (INT)(sizeof(tbl::{sym}) / sizeof({t[4]}));',
            '  for (INT i = 0; i < n; i++) out[i] = (INT)p[i];',
            '  return n;',
            '}',
        ]
    shim += ['}', '']
    path = os.path.join(REPO, 'crates', 'cref', 'shim', 'aacdec_tables_glue.cpp')
    open(path, 'w').write('\n'.join(shim))
    print(f'wrote {os.path.relpath(path, REPO)}')


if __name__ == '__main__':
    main()
