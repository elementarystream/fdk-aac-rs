#!/usr/bin/env python3
"""Generate the constant tables of libSBRdec from the C++ reference.

Writes `crates/sbrdec/src/<module>/tables.rs` for every module of the crate that has tables
(`sbr_rom`, `env_extr`, `hbe`, `hfgen_pre_flat`, `psdec`, `pvc_dec`, `sbrdec_drc`), and the
differential test of the tables: the shims `crates/cref/shim/sbrdec_tables_<module>.cpp` and
`crates/cref/tests/sbrdec/tables.rs`.

Nothing is retyped: for every C++ source file, one small program includes the source file (so
that file-static tables are visible) and prints the scalar values of every listed table, field
by field for struct tables. Function-local tables are copied verbatim from the source text to
file scope (see `L`), so their initializers are also evaluated by the compiler. The program is
compiled and run with scripts/dump_table.py's
compiler setup for arm64 and x86_64 (on Apple silicon), and the generator fails if the two
architectures print different values.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/sbrdec/src/sbr_rom/gen_tables.py
"""
