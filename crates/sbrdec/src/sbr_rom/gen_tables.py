RUST = {'UCHAR': 'u8', 'SCHAR': 'i8', 'SHORT': 'i16', 'FIXP_SGL': 'i16', 'FIXP_QTW': 'i16',
        'USHORT': 'u16', 'LONG': 'i32', 'FIXP_DBL': 'i32', 'INT': 'i32', 'int': 'i32',
        'UINT': 'u32'}


class T:
    """A flat or two-dimensional table: `expr` is the C expression of the first element's
    array, `dims` the Rust dimensions (outer first)."""

    def __init__(self, cname, ctype, dims, rname, expr=None, vis='pub', doc=None):
        self.cname, self.ctype, self.dims, self.rname = cname, ctype, dims, rname
        self.expr = expr or cname
        self.vis = 'pub'  # the table test reads every table
        self.doc = doc

    def count(self):
        n = 1
        for d in self.dims:
            n *= d
        return n

    def c_print(self):
        return (f'  {{ const {self.ctype}* p = (const {self.ctype}*)(const void*)(&{self.expr});\n'
                f'    for (long i = 0; i < {self.count()}; i++) printf("%lld\\n", (long long)p[i]); }}\n')

    def rust(self, vals):
        rt = RUST[self.ctype]
        if len(self.dims) == 1:
            ty = f'[{rt}; {self.dims[0]}]'
            body = fmt_list([fmt(v, rt) for v in vals], 12 if rt in ('u8', 'i8') else 8)
        else:
            inner = self.dims[1]
            ty = f'[[{rt}; {inner}]; {self.dims[0]}]'
            rows = []
            for r in range(self.dims[0]):
                row = vals[r * inner:(r + 1) * inner]
                rows.append('[' + ', '.join(fmt(v, rt) for v in row) + ']')
            body = ''.join(f'    {row},\n' for row in rows)
        doc = self.doc or f'`{self.cname}`'
        return f'/// {doc}\n{self.vis} static {self.rname}: {ty} = [\n{body}];\n'


class L(T):
    """A function-local table of `func`: its declaration (`[static] [const] TYPE name[..] =
    {...};`) is copied verbatim from the source text to file scope after the source, renamed to
    `local_<func>_<name>`, so that the dump program and the shim can read it. The values are
    still computed by the compiler from the reference's own initializer."""

    def __init__(self, func, cname, ctype, dims, rname, doc=None):
        super().__init__(cname, ctype, dims, rname, expr=f'local_{func}_{cname}',
                         doc=doc or f'`{cname}` of `{func}()` (a function-local table)')
        self.func = func

    def decl(self, text):
        """The file-scope copy of the declaration, found in the body of `func`."""
        start = re.search(r'\b' + re.escape(self.func) + r'\s*\(', text)
        if not start:
            sys.exit(f'error: function {self.func} not found')
        m = re.compile(r'^\s*(?:static\s+)?(?:const\s+)?(\w+)\s+' + re.escape(self.cname) +
                       r'\s*((?:\[[^\]]*\])+)\s*=\s*(\{.*?\});', re.M | re.S).search(text, start.end())
        if not m:
            sys.exit(f'error: table {self.cname} of {self.func} not found')
        return f'static const {m.group(1)} {self.expr}{m.group(2)} = {m.group(3)};\n'


class S:
    """A table of structures: `fields` is a list of (C field, C type, count, Rust field)."""

    def __init__(self, cname, n, fields, rname, rtype, vis='pub', single=False, doc=None):
        self.cname, self.n, self.fields, self.rname, self.rtype = cname, n, fields, rname, rtype
        self.vis, self.single, self.doc = 'pub', single, doc

    def count(self):
        return self.n * sum(f[2] for f in self.fields)

    def c_print(self):
        out = ''
        for i in range(self.n):
            elem = self.cname if self.single else f'{self.cname}[{i}]'
            for (cf, ct, cnt, _rf) in self.fields:
                if cnt == 1:
                    out += f'  printf("%lld\\n", (long long){elem}.{cf});\n'
                else:
                    out += (f'  for (int k = 0; k < {cnt}; k++) '
                            f'printf("%lld\\n", (long long){elem}.{cf}[k]);\n')
        return out

    def rust(self, vals):
        it = iter(vals)
        elems = []
        for _ in range(self.n):
            parts = []
            for (_cf, ct, cnt, rf) in self.fields:
                rt = RUST[ct]
                if cnt == 1:
                    parts.append(f'{rf}: {fmt(next(it), rt)}')
                else:
                    parts.append(f'{rf}: [' + ', '.join(fmt(next(it), rt) for _ in range(cnt)) + ']')
            elems.append(f'{self.rtype} {{ ' + ', '.join(parts) + ' }')
        doc = self.doc or f'`{self.cname}`'
        if self.single:
            return f'/// {doc}\n{self.vis} static {self.rname}: {self.rtype} = {elems[0]};\n'
        body = ''.join(f'    {e},\n' for e in elems)
        return f'/// {doc}\n{self.vis} static {self.rname}: [{self.rtype}; {self.n}] = [\n{body}];\n'


def fmt(v, rt):
    v = int(v)
    if rt == 'i32' and (v > 0xFFFF or v < -0xFFFF):
        return f'0x{v:08X}' if v >= 0 else f'0x{v & 0xFFFFFFFF:08X}u32 as i32'
    return str(v)


def fmt_list(items, per_line):
    return ''.join('    ' + ', '.join(items[i:i + per_line]) + ',\n'
                   for i in range(0, len(items), per_line))


