def local_decls(src, tables):
    text = open(os.path.join(dump_table.CDIR, src)).read()
    return ''.join(t.decl(text) for t in tables if isinstance(t, L))


def run(src, tables):
    path = os.path.join(dump_table.CDIR, src)
    prog = f'#include "{path}"\n#include <stdio.h>\n{local_decls(src, tables)}int main() {{\n'
    for t in tables:
        prog += t.c_print()
    prog += '  return 0;\n}\n'
    results = {arch: dump_table.dump(prog, arch) for arch in dump_table.archs(None)}
    first = next(iter(results.values()))
    for arch, out in results.items():
        if out != first:
            sys.exit(f'error: the tables of {src} differ between architectures')
    return [int(v) for v in first]


SHIM_RENAMES = {'sbrdec_drc': ['sbrDecoder_drcApplySlot']}

SHIM_HEADER = '''// GENERATED by `python3 crates/sbrdec/src/sbr_rom/gen_tables.py`; do not edit.
//
// Shim of the table test of fdk_aac_rs_sbrdec::{module} (tests/sbrdec/tables.rs): a copy of
// {src} in a namespace (so that its file-static tables are visible) writes the values of every
// table, field by field for struct tables, in the order of the generator.

#include "cref_common.h"
'''

TEST_HEADER = '''// GENERATED by `python3 crates/sbrdec/src/sbr_rom/gen_tables.py`; do not edit.
//
// Differential tests of the constant tables of fdk_aac_rs_sbrdec against the C++ reference:
// every value of every table (field by field for struct tables) is compared with the table of
// a copy of the C++ source compiled into the shims shim/sbrdec_tables_*.cpp.

/// Compares the values of one table with the reference values from `pos` on.
fn check(name: &str, reference: &[i32], pos: &mut usize, port: &[i32]) {
    let r = &reference[*pos..*pos + port.len()];
    if let Some(k) = (0..port.len()).find(|&k| r[k] != port[k]) {
        panic!("{name}[{k}]: port {}, reference {}", port[k], r[k]);
    }
    *pos += port.len();
}
'''


def shim_dump(t):
    """C code writing the values of a table to out[n++] (inside namespace tbl)."""
    if isinstance(t, T):
        return (f'  {{ const {t.ctype}* p = (const {t.ctype}*)(const void*)(&{t.expr});\n'
                f'    for (long i = 0; i < {t.count()}; i++) out[n++] = (INT)p[i]; }}\n')
    code = ''
    for i in range(t.n):
        elem = t.cname if t.single else f'{t.cname}[{i}]'
        for (cf, _ct, cnt, _rf) in t.fields:
            if cnt == 1:
                code += f'  out[n++] = (INT){elem}.{cf};\n'
            else:
                code += f'  for (int k = 0; k < {cnt}; k++) out[n++] = (INT){elem}.{cf}[k];\n'
    return code


def rust_flatten(t):
    """Rust code pushing the values of a port table to `v`."""
    if isinstance(t, T):
        it = f'{t.rname}.iter()' + ('.flatten()' if len(t.dims) == 2 else '')
        return f'        for &x in {it} {{\n            v.push(x as i32);\n        }}\n'

    def body(ind):
        b = ''
        for (_cf, _ct, cnt, rf) in t.fields:
            if cnt == 1:
                b += f'{ind}v.push(e.{rf} as i32);\n'
            else:
                b += f'{ind}for &x in e.{rf}.iter() {{\n{ind}    v.push(x as i32);\n{ind}}}\n'
        return b
    if t.single:
        return f'        let e = &{t.rname};\n' + body('        ')
    return f'        for e in {t.rname}.iter() {{\n' + body('            ') + '        }\n'


def main():
    test = TEST_HEADER
    for module, src, uses, tables in MODULES:
        vals = run(src, tables)
        base = os.path.basename(src)
        out = HEADER.format(src=src, base=base)
        out += '\n#![allow(clippy::unreadable_literal)]\n'
        if uses:
            out += '\n' + uses
        pos = 0
        for t in tables:
            n = t.count()
            out += '\n' + t.rust(vals[pos:pos + n])
            pos += n
        assert pos == len(vals)
        os.makedirs(os.path.join(SRC_DIR, module), exist_ok=True)
        open(os.path.join(SRC_DIR, module, 'tables.rs'), 'w').write(out)
        print(f'{module}: {len(tables)} tables, {len(vals)} values')

        # The shim: the direct includes of the source at global scope, the source itself in a
        # namespace.
        text = open(os.path.join(dump_table.CDIR, src)).read()
        incs = re.findall(r'^#include "([^"]+)"', text, re.M)
        shim = SHIM_HEADER.format(module=module, src=src)
        shim += ''.join(f'#include "{h}"\n' for h in incs)
        # Functions of the source that are called with arguments of global types: argument
        # dependent lookup would also find the global declaration (ambiguous call).
        for f in SHIM_RENAMES.get(module, []):
            shim += f'#define {f} tbl_{f}\n'
        shim += f'\nnamespace tbl {{\n#include "{src}"\n\n{local_decls(src, tables)}'
        shim += 'static INT dump(INT *out) {\n  INT n = 0;\n'
        for t in tables:
            shim += shim_dump(t)
        shim += '  return n;\n}\n}  // namespace tbl\n\nextern "C" {\n'
        shim += f'INT cref_sbrdec_tables_{module}(INT *out) {{ return tbl::dump(out); }}\n}}\n'
        open(os.path.join(REPO, 'crates', 'cref', 'shim', f'sbrdec_tables_{module}.cpp'), 'w').write(shim)

        test += f'\n#[test]\nfn {module}() {{\n'
        test += f'    use fdk_aac_rs_cref::sbrdec_tables_{module}::cref_sbrdec_tables_{module};\n'
        test += f'    use fdk_aac_rs_sbrdec::{module}::tables::*;\n'
        test += f'    let mut reference = vec![0i32; {len(vals)}];\n'
        test += f'    let n = unsafe {{ cref_sbrdec_tables_{module}(reference.as_mut_ptr()) }};\n'
        test += f'    assert_eq!(n, {len(vals)});\n    let mut pos = 0;\n'
        for t in tables:
            test += '    {\n        let mut v = Vec::new();\n'
            test += rust_flatten(t)
            test += f'        check("{t.cname}", &reference, &mut pos, &v);\n    }}\n'
        test += f'    assert_eq!(pos, {len(vals)});\n}}\n'
    open(os.path.join(REPO, 'crates', 'cref', 'tests', 'sbrdec', 'tables.rs'), 'w').write(test)


if __name__ == '__main__':
    main()
