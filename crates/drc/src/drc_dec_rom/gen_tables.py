#!/usr/bin/env python3
"""Generate crates/drc/src/drc_dec_rom/tables.rs from the C++ reference.

Every value comes from scripts/dump_table.py, which compiles libDRCdec/src/drcDec_rom.cpp on arm64
and x86_64 and fails if the two give different values. Nothing is retyped:

* The scalar tables are dumped with their element type.
* The CUSTOM_DRC_CHAR_SIGMOID tables (8 bytes: gain, ioRatio, exp, flipSign + padding) are dumped
  as SHORT and wrapped into `sigmoid(gain, ioRatio, exp, flipSign | padding << 8)`.
* The CUSTOM_DRC_CHAR_NODES tables (22 bytes: characteristicNodeCount + padding, nodeLevel[5],
  nodeGain[5]) are dumped as SHORT and wrapped into `nodes([...])`.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/drc/src/drc_dec_rom/gen_tables.py
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
DUMP = os.path.join(REPO, 'scripts', 'dump_table.py')
SRC = 'libDRCdec/src/drcDec_rom.cpp'

HEADER = '''// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libDRCdec/src/drcDec_rom.cpp.
//
// GENERATED by `python3 crates/drc/src/drc_dec_rom/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! The constant tables of `drcDec_rom.cpp`.

use crate::drc_dec_types::{CustomDrcCharNodes, CustomDrcCharSigmoid};
use fdk_aac_rs_fdk::common_fix::{FixpDbl, FixpSgl};

const fn sigmoid(v: [i16; 4]) -> CustomDrcCharSigmoid {
    CustomDrcCharSigmoid {
        gain: v[0],
        io_ratio: v[1],
        exp: v[2],
        flip_sign: v[3] as u8,
        _pad0: (v[3] >> 8) as u8,
    }
}

const fn nodes(v: [i16; 11]) -> CustomDrcCharNodes {
    CustomDrcCharNodes {
        characteristic_node_count: v[0] as u8,
        _pad0: (v[0] >> 8) as u8,
        node_level: [v[1], v[2], v[3], v[4], v[5]],
        node_gain: [v[6], v[7], v[8], v[9], v[10]],
    }
}
'''

# (C name, Rust name, dump type, Rust element type, struct wrapper, words per struct)
TABLES = [
    ('deltaGain_codingProfile_0_1_huffman', 'DELTA_GAIN_CODING_PROFILE_0_1_HUFFMAN', 'SCHAR', None,
     'pairs', 2),
    ('deltaGain_codingProfile_2_huffman', 'DELTA_GAIN_CODING_PROFILE_2_HUFFMAN', 'SCHAR', None,
     'pairs', 2),
    ('slopeSteepness', 'SLOPE_STEEPNESS', 'SHORT', 'FixpSgl', None, 1),
    ('slopeSteepness_huffman', 'SLOPE_STEEPNESS_HUFFMAN', 'SCHAR', None, 'pairs', 2),
    ('downmixCoeff', 'DOWNMIX_COEFF', 'LONG', 'FixpDbl', None, 1),
    ('downmixCoeffV1', 'DOWNMIX_COEFF_V1', 'LONG', 'FixpDbl', None, 1),
    ('cicpDrcCharSigmoidLeft', 'CICP_DRC_CHAR_SIGMOID_LEFT', 'SHORT', 'CustomDrcCharSigmoid',
     'sigmoid', 4),
    ('cicpDrcCharSigmoidRight', 'CICP_DRC_CHAR_SIGMOID_RIGHT', 'SHORT', 'CustomDrcCharSigmoid',
     'sigmoid', 4),
    ('cicpDrcCharNodesLeft', 'CICP_DRC_CHAR_NODES_LEFT', 'SHORT', 'CustomDrcCharNodes', 'nodes',
     11),
    ('cicpDrcCharNodesRight', 'CICP_DRC_CHAR_NODES_RIGHT', 'SHORT', 'CustomDrcCharNodes', 'nodes',
     11),
]


def dump(cname, ctype):
    cmd = [sys.executable, DUMP, SRC, cname, ctype, '--per-line', '1000000']
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    body = out.split('[', 2)[2].split('];')[0]
    vals = [v.strip() for v in body.replace('\n', ' ').split(',') if v.strip()]
    return vals, f'{SRC} {cname} {ctype}'


def main():
    out = [HEADER]
    for cname, rname, ctype, rtype, wrap, words in TABLES:
        vals, cmd = dump(cname, ctype)
        assert len(vals) % words == 0, cname
        n = len(vals) // words
        out.append(f'/// `{cname}`\n///\n/// `scripts/dump_table.py {cmd}`')
        if wrap == 'pairs':
            out.append(f'pub static {rname}: [[i8; 2]; {n}] = [')
            for i in range(n):
                out.append(f'    [{vals[2 * i]}, {vals[2 * i + 1]}],')
        elif wrap is None:
            out.append(f'pub static {rname}: [{rtype}; {n}] = [')
            for v in vals:
                out.append(f'    {v},')
        else:
            out.append(f'pub static {rname}: [{rtype}; {n}] = [')
            for i in range(n):
                out.append(f'    {wrap}([{", ".join(vals[words * i:words * (i + 1)])}]),')
        out.append('];')
        out.append('')
    path = os.path.join(HERE, 'tables.rs')
    open(path, 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
