#!/usr/bin/env python3
"""Generate crates/sacenc/src/sacenc_bitstream/tables.rs from the C++ reference.

Every table of libSACenc/src/sacenc_bitstream.cpp is dumped with scripts/dump_table.py, which compiles the C++ source on
arm64 and x86_64 and fails if the two give different values. Nothing is retyped. Structure
tables are dumped as their scalar fields (a pointer as the index of the table it points to),
collected by a small C++ prelude.

Usage (from the repository root; needs the reference sources, see scripts/setup_reference.sh):
  python3 crates/sacenc/src/sacenc_bitstream/gen_tables.py
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
SRC = 'libSACenc/src/sacenc_bitstream.cpp'

HEADER = """// fdk-aac-rs: Third-Party Modified Version of the Fraunhofer FDK AAC Codec Library for Android.
// A Rust port of fdk-aac 2.0.3. See LICENSE.txt for the complete license text.
//
// Ported from libSACenc/src/sacenc_bitstream.cpp.
//
// GENERATED by `python3 crates/sacenc/src/sacenc_bitstream/gen_tables.py`; do not edit. Every table is
// dumped with scripts/dump_table.py (the command is given at each table), which checks that the
// arm64 and x86_64 builds give the same values.

//! The tables of `sacenc_bitstream.cpp`.
"""

# (doc, symbol, element type, extra arguments)
TABLES = [
    ('`SampleRateTable`', 'SampleRateTable', 'INT', ['--name', 'SAMPLE_RATE_TABLE', '--per-line', '7']),
    ('`FreqResBinTable_LD`', 'FreqResBinTable_LD', 'UCHAR', ['--name', 'FREQ_RES_BIN_TABLE_LD']),
    ('`FreqResStrideTable_LD`', 'FreqResStrideTable_LD', 'UCHAR', ['--name', 'FREQ_RES_STRIDE_TABLE_LD']),
]


def main():
    out = [HEADER]
    for doc, sym, ty, extra in TABLES:
        args = [SRC, sym, ty] + extra
        cmd = 'scripts/dump_table.py ' + ' '.join(repr(a) if (' ' in a or ';' in a) else a for a in args)
        r = subprocess.run([sys.executable, os.path.join(REPO, 'scripts', 'dump_table.py')] + args,
                           capture_output=True, text=True, check=True, cwd=REPO)
        out.append('')
        out.append(f'/// {doc}')
        out.append('///')
        out.append(f'/// `{cmd}`')
        out.append(r.stdout.rstrip())
    path = os.path.join(HERE, 'tables.rs')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    subprocess.run(['rustfmt', '--edition', '2021', path], check=True)


if __name__ == '__main__':
    main()
