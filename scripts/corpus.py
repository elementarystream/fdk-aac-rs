#!/usr/bin/env python3
"""Test corpus of fdk-aac-rs: manifest scripts/corpus.json (PORTING.md, "End-to-end corpus").

scripts/corpus.json is the manifest that scripts/e2e.py runs (PORTING.md, "Reference harness"): its
"entries" list holds one {name, kind, input, args} record per decoder or encoder run, with
the arguments of fdkdec-ref / fdkenc-ref. The entries are generated by `pin` from the rest of the
manifest:

- external material by path below work/ and SHA-256 (local audio; never committed, local only);
- conformance bitstreams from work/conformance/index.json (scripts/fetch_conformance.py), pinned by
  name and MD5;
- Fraunhofer playback test streams by URL (local only: personal use, never fetched by this tool);
- synthetic signals generated deterministically by this file (pinned by set digests);
- the encoder configuration factors, of which the encoder entries are a pairwise covering.

Entries whose name starts with "local-" need local-only inputs; shared runs skip them
(scripts/e2e.py --filter '^(?!local-)').

Commands:
  gen [--set NAME ...] [--pin]   generate the synthetic signals into work/corpus-gen/ (s16le raw
                                 files with a JSON sidecar each; sets: rates, layouts, matrix =
                                 the synthetic inputs of the encoder entries) and the ancillary
                                 data file; --pin records the digests in corpus.json
  pin                            regenerate the entries of corpus.json (needs index.json)
  check [--tags T,...] [-v]      verify the hashes of the present inputs, list the missing ones
  list [--tags T,...] [--kind K] [--inputs] [--fresh] [--json] [--count]
                                 print the entries (or the input files)
  fraunhofer [--pin]             print the download instructions of the local-only Fraunhofer
                                 streams; --pin records the SHA-256 of the copies present in
                                 work/fraunhofer/
  scan [--pin]                   hash the local audio of work/{corpus,mx,songs,rw,pcm} and compare
                                 with corpus.json; --pin rewrites the external entries

Synthetic signals are computed with integer arithmetic and IEEE double additions and
multiplications only (no libm), so the files are identical on every platform; `check` compares
them with the digests in corpus.json.

Python 3 standard library only.
"""
