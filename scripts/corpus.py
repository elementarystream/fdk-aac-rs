def file_hash(path, algo='sha256'):
    h = hashlib.new(algo)
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


# --- deterministic signal generation -----------------------------------------------------------

TWO_PI = 6.283185307179586


def sin_turns(t):
    """sin(2*pi*t) for t in [0, 1), with + and * only (Taylor series after reduction to
    [0, pi/2]); identical results on every IEEE-754 platform."""
    neg = False
    if t >= 0.5:
        t -= 0.5
        neg = True
    if t > 0.25:
        t = 0.5 - t
    x = TWO_PI * t
    x2 = x * x
    # Horner form of x - x^3/3! + ... - x^19/19!
    s = 1.0
    for k in (19, 17, 15, 13, 11, 9, 7, 5, 3):
        s = 1.0 - s * x2 / float(k * (k - 1))
    s *= x
    return -s if neg else s


def to_s16(v):
    """Round half up and clip to the 16-bit range."""
    i = int(v + 32768.5) - 32768  # floor(v + 0.5) for v > -32768.5
    return 32767 if i > 32767 else (-32768 if i < -32768 else i)


def xorshift32(seed):
    x = seed & 0xffffffff
    while True:
        x ^= (x << 13) & 0xffffffff
        x ^= x >> 17
        x ^= (x << 5) & 0xffffffff
        yield x


def tone(rate, n, freq, amp):
    out = array.array('h', bytes(2 * n))
    for i in range(n):
        out[i] = to_s16(amp * sin_turns(((i * freq) % rate) / rate))
    return out


def signal(name, rate, n, spec):
    """Mono signal `name` (see SIGNALS in corpus.json) of n samples at `rate`."""
    kind = spec['kind']
    if kind == 'constant':
        return array.array('h', [spec['value']]) * n
    if kind == 'tone':
        return tone(rate, n, spec['freq'], spec['amp'])
    if kind == 'nyquist':
        a = spec['amp']
        return array.array('h', [a, -a]) * (n // 2) + array.array('h', [a] * (n % 2))
    if kind == 'impulses':
        out = array.array('h', bytes(2 * n))
        step = rate * spec['period_ms'] // 1000
        for k, i in enumerate(range(step // 2, n, step)):
            out[i] = spec['amp'] if k % 2 == 0 else -spec['amp'] - 1
        return out
    if kind == 'spike':
        out = array.array('h', bytes(2 * n))
        out[min(n - 1, rate * spec['at_ms'] // 1000)] = spec['amp']
        return out
    if kind == 'noise':
        g = xorshift32(spec['seed'] + rate)
        lo, hi = spec['range']
        span = hi - lo + 1
        return array.array('h', (lo + (next(g) % span) for _ in range(n)))
    if kind == 'sweep':
        # Linear sweep f0 -> f1 (fraction of the rate): phase(i) = (2 N f0 i + (f1 - f0) i^2)
        # / (2 N rate) turns, reduced exactly with integers.
        f0 = spec['f0']
        f1 = rate * spec['f1_num'] // spec['f1_den']
        den = 2 * n * rate
        out = array.array('h', bytes(2 * n))
        a = spec['amp']
        for i in range(n):
            num = (2 * n * f0 * i + (f1 - f0) * i * i) % den
            out[i] = to_s16(a * sin_turns(num / den))
        return out
    raise ValueError(f'{name}: unknown signal kind {kind}')


def interleave(mono, channels, shift):
    """Channel c is the mono signal rotated by c * shift samples (so channels differ)."""
    n = len(mono)
    out = array.array('h', bytes(2 * n * channels))
    for c in range(channels):
        s = (c * shift) % n if n else 0
        out[c::channels] = mono[n - s:] + mono[:n - s] if s else mono
    return out


def syn_name(sig, rate, layout):
    return f'syn_{sig}_{rate}_{layout}'


class Generator:
    def __init__(self, m):
        self.m = m
        self.syn = m['synthetic']
        self.cache = {}

    def mono(self, sig, rate):
        key = (sig, rate)
        if key not in self.cache:
            n = rate * self.syn['duration_ms'] // 1000
            self.cache = {k: v for k, v in self.cache.items() if k[1] == rate}
            self.cache[key] = signal(sig, rate, n, self.syn['signals'][sig])
        return self.cache[key]

    def write(self, sig, rate, layout):
        lay = self.syn['layouts'][layout]
        name = syn_name(sig, rate, layout)
        raw = os.path.join(GEN, name + '.s16le')
        side = os.path.join(GEN, name + '.json')
        if os.path.exists(side) and os.path.exists(raw):
            with open(side) as f:
                meta = json.load(f)
            if meta.get('generator_version') == GENERATOR_VERSION and \
                    meta.get('size') == os.path.getsize(raw):
                return name, meta['sha256']
        data = interleave(self.mono(sig, rate), lay['channels'],
                          rate * self.syn['channel_shift_ms'] // 1000)
        if sys.byteorder == 'big':
            data.byteswap()
        b = data.tobytes()
        os.makedirs(GEN, exist_ok=True)
        with open(raw + '.part', 'wb') as f:
            f.write(b)
        os.replace(raw + '.part', raw)
        meta = {'file': name + '.s16le', 'format': 's16le', 'rate': rate,
                'channels': lay['channels'], 'layout': layout, 'channel_mode': lay['channel_mode'],
                'channel_order': 'MPEG', 'signal': sig, 'signal_spec': self.syn['signals'][sig],
                'samples_per_channel': len(b) // (2 * lay['channels']), 'size': len(b),
                'sha256': hashlib.sha256(b).hexdigest(), 'generator': 'scripts/corpus.py',
                'generator_version': GENERATOR_VERSION}
        with open(side, 'w') as f:
            json.dump(meta, f, indent=1)
        return name, meta['sha256']


def set_members(m, name):
    syn = m['synthetic']
    if name == 'matrix':
        out = set()
        for case in encoder_cases(m):
            mt = re.fullmatch(r'corpus-gen/syn_(.+)_(\d+)_([^_]+)\.s16le', case['input'])
            if mt:
                out.add((mt.group(1), int(mt.group(2)), mt.group(3)))
        return sorted(out)
    s = syn['sets'][name]
    sigs = s.get('signals', sorted(syn['signals']))
    return sorted(itertools.product(sigs, s['rates'], s['layouts']))


def set_digest(hashes):
    return hashlib.sha256(''.join(f'{n} {h}\n' for n, h in sorted(hashes)).encode()).hexdigest()


def cmd_gen(args, m):
    g = Generator(m)
    names = args.set or list(m['synthetic']['sets'])
    for sname in names:
        members = set_members(m, sname)
        hashes = []
        for k, (sig, rate, layout) in enumerate(sorted(members, key=lambda x: (x[1], x[0], x[2]))):
            hashes.append(g.write(sig, rate, layout))
        d = set_digest(hashes)
        s = m['synthetic']['sets'][sname]
        size = sum(os.path.getsize(os.path.join(GEN, n + '.s16le')) for n, _ in hashes)
        status = 'pinned' if s.get('digest') == d else (
            'DIFFERS from corpus.json' if s.get('digest') else 'not pinned')
        print(f'{sname}: {len(hashes)} files, {size / 1e6:.1f} MB, digest {d[:16]}... ({status})')
        if args.pin:
            s['digest'] = d
            s['files'] = len(hashes)
            s['bytes'] = size
    anc = m['encoder_matrix']['anc_file']
    p = os.path.join(WORK, anc['path'])
    lines = ''.join(bytes((k * anc['bytes_per_call'] + i) & 0xff
                          for i in range(anc['bytes_per_call'])).hex() + '\n'
                    for k in range(anc['calls']))
    with open(p, 'w') as f:
        f.write(lines)
    h = hashlib.sha256(lines.encode()).hexdigest()
    print(f'{anc["path"]}: {anc["calls"]} lines, sha256 {h[:16]}... '
          f'({"pinned" if anc.get("sha256") == h else "not pinned"})')
    if args.pin:
        anc['sha256'] = h
        save_manifest(m)
        print('corpus.json updated')


# --- encoder matrix: pairwise covering ---------------------------------------------------------

def _profile(m, name):
    return m['encoder_matrix']['profiles'][name]


def violates(m, c):
    """True if the partial assignment c breaks a constraint of corpus.json
    encoder_matrix.constraints (each check runs once its fields are assigned)."""
    em = m['encoder_matrix']
    p = _profile(m, c['profile']) if 'profile' in c else None
    layouts = m['synthetic']['layouts']
    ch = layouts[c['layout']]['channels'] if 'layout' in c else None
    tt = c.get('transport')
    # C1: stereo-only profiles
    if p and ch is not None and p.get('stereo_only') and ch != 2:
        return True
    # C12: channel modes a profile cannot encode
    if p and 'layout' in c and layouts[c['layout']]['channel_mode'] in \
            p.get('excluded_channel_modes', []):
        return True
    # C2: frame lengths per profile
    if p and 'frame_length' in c and c['frame_length'] not in p['frame_lengths']:
        return True
    # C3: sampling-rate range per profile
    if p and 'rate' in c and not (p.get('min_rate', 0) <= c['rate'] <= p.get('max_rate', 10**6)):
        return True
    # C4: ADIF and ADTS carry MPEG-2 style profiles only (no ER object types)
    if p and tt in ('adif', 'adts') and not p.get('adts_ok'):
        return True
    # C6: AudioMuxVersion only varies with LATM/LOAS
    if tt is not None and tt not in em['latm_transports'] and c.get('audiomuxver', 0) != 0:
        return True
    # C7: explicit backward-compatible signaling with LATM/LOAS needs AudioMuxVersion 1
    if tt in em['latm_transports'] and c.get('signaling') == 1 and c.get('audiomuxver') == 0:
        return True
    # C8: CRC only varies with ADTS
    if tt is not None and tt != 'adts' and c.get('crc', 0) != 0:
        return True
    # C9: signaling only varies with profiles that have an extension object type (SBR)
    if p and not p.get('signaling_varies') and c.get('signaling', 0) != 0:
        return True
    # C10: the channel order only varies with three or more channels
    if ch is not None and ch < 3 and c.get('channel_order', 0) != 0:
        return True
    return False


def completable(m, factors, c, order):
    """Whether the partial case c can be completed (depth-first search)."""
    if violates(m, c):
        return False
    for f in order:
        if f not in c:
            for v in factors[f]:
                c[f] = v
                if completable(m, factors, c, order):
                    del c[f]
                    return True
                del c[f]
            return False
    return True


_PAIRWISE = {}


def pairwise(m, factors, fixed=None):
    """Greedy deterministic pairwise covering of `factors` ({name: [values]}) under the
    constraints; `fixed` values are part of every case. Infeasible pairs are skipped."""
    fixed = fixed or {}
    key = json.dumps([factors, fixed, m['encoder_matrix'], m['synthetic']['layouts']],
                     sort_keys=True)
    if key not in _PAIRWISE:
        _PAIRWISE[key] = _pairwise(m, factors, fixed)
    cases, n = _PAIRWISE[key]
    return [dict(c) for c in cases], n


def _pairwise(m, factors, fixed):
    order = [f for f in factors if f not in fixed]
    uncovered = []
    for i, a in enumerate(order):
        for b in order[i + 1:]:
            for va in factors[a]:
                for vb in factors[b]:
                    c = dict(fixed, **{a: va, b: vb})
                    if completable(m, factors, c, order):
                        uncovered.append(((a, va), (b, vb)))
    uncov = set(uncovered)
    cases = []
    for pair in uncovered:
        if pair not in uncov:
            continue
        (a, va), (b, vb) = pair
        c = dict(fixed, **{a: va, b: vb})
        for f in order:
            if f in c:
                continue
            best, best_gain = None, -1
            for v in factors[f]:
                c[f] = v
                if completable(m, factors, c, order):
                    gain = sum(1 for g in order if g in c and g != f and
                               (((g, c[g]), (f, v)) if order.index(g) < order.index(f)
                                else ((f, v), (g, c[g]))) in uncov)
                    if gain > best_gain:
                        best, best_gain = v, gain
                del c[f]
            c[f] = best
        for i, x in enumerate(order):
            for y in order[i + 1:]:
                uncov.discard(((x, c[x]), (y, c[y])))
        cases.append(c)
    return cases, len(uncovered)


def bitrate_args(m, c, channels):
    p = _profile(m, c['profile'])
    b = c['bitrate']
    if b.startswith('vbr'):
        return ['--param', f'AACENC_BITRATEMODE={int(b[3:])}']
    per_ch = p['cbr_per_channel'][b[4:]]
    return ['--param', 'AACENC_BITRATEMODE=0', '--param', f'AACENC_BITRATE={per_ch * channels}']


def safe_name(s):
    return re.sub(r'[^A-Za-z0-9._+-]', '_', s)


def syn_path(sig, rate, layout):
    return f'corpus-gen/{syn_name(sig, rate, layout)}.s16le'


def case_args(m, c, rate, layout):
    em = m['encoder_matrix']
    p = _profile(m, c['profile'])
    lay = m['synthetic']['layouts'][layout]
    mode = p.get('channel_mode', lay['channel_mode'])
    a = ['-f', 's16le', '--rate', str(rate), '--channels', str(lay['channels']),
         '--param', f'AACENC_AOT={p["aot"]}', '--param', f'AACENC_SAMPLERATE={rate}']
    if 'sbr_mode' in p:
        a += ['--param', f'AACENC_SBR_MODE={p["sbr_mode"]}']
    a += ['--param', f'AACENC_CHANNELMODE={mode}']
    a += bitrate_args(m, c, lay['channels'])
    a += ['--param', f'AACENC_AFTERBURNER={c["afterburner"]}',
          '--param', f'AACENC_GRANULE_LENGTH={c["frame_length"]}',
          '--param', f'AACENC_TRANSMUX={em["transmux"][c["transport"]]}',
          '--param', f'AACENC_PROTECTION={c["crc"]}',
          '--param', f'AACENC_SIGNALING_MODE={c["signaling"]}',
          '--param', f'AACENC_AUDIOMUXVER={c["audiomuxver"]}',
          '--param', f'AACENC_METADATA_MODE={c["metadata"]}',
          '--param', f'AACENC_CHANNELORDER={c["channel_order"]}']
    a += em['anc_args'][c['anc']]
    a += em['metadata_args'][str(c['metadata'])]
    return a


def encoder_cases(m):
    """All encoder entries: the pairwise covering over the synthetic inputs, the core cases (a
    pairwise covering of the configuration per core input) and the explicit cases."""
    em = m['encoder_matrix']
    conf = dict(em['factors'])
    out = []
    full = dict(conf)
    full.update(em['input_factors'])
    cases, _ = pairwise(m, full)
    for k, c in enumerate(cases):
        out.append({'name': f'enc-pw-{k + 1:04d}', 'kind': 'encode',
                    'input': syn_path(c['signal'], c['rate'], c['layout']),
                    'args': case_args(m, c, c['rate'], c['layout']),
                    'tags': ['encoder', 'pairwise'], 'factors': c})
    for ci in em['core_inputs']:
        fixed = {'rate': ci['rate'], 'layout': ci['layout']}
        f2 = dict(conf, rate=[ci['rate']], layout=[ci['layout']])
        cases, _ = pairwise(m, f2, fixed)
        local = bool(ci.get('local_only'))
        if 'signal' in ci:
            ci = dict(ci, input=syn_path(ci['signal'], ci['rate'], ci['layout']))
        for k, c in enumerate(cases):
            e = {'name': f'{"local-" if local else ""}enc-core-{ci["id"]}-{k + 1:03d}',
                 'kind': 'encode', 'input': ci['input'],
                 'args': case_args(m, c, ci['rate'], ci['layout']),
                 'tags': ['encoder', 'core'] + (['local-only'] if local else []), 'factors': c}
            if local:
                e['local_only'] = True
            out.append(e)
    for e in em.get('explicit_cases', []):
        out.append(dict(e, kind='encode', tags=['encoder', 'explicit'] + e.get('tags', [])))
    return out


def matrix_stats(m):
    em = m['encoder_matrix']
    conf = dict(em['factors'])
    full = dict(conf)
    full.update(em['input_factors'])
    cases, pairs = pairwise(m, full)
    st = {'pairwise_feasible_pairs': pairs, 'pairwise_cases': len(cases), 'core': {}}
    for ci in em['core_inputs']:
        f2 = dict(conf, rate=[ci['rate']], layout=[ci['layout']])
        c2, _ = pairwise(m, f2, {'rate': ci['rate'], 'layout': ci['layout']})
        st['core'][ci['id']] = len(c2)
    st['core_cases'] = sum(st['core'].values())
    st['explicit_cases'] = len(em.get('explicit_cases', []))
    st['full_cross_product'] = 1
    for v in full.values():
        st['full_cross_product'] *= len(v)
    return st


