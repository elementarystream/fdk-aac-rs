def load_index():
    p = os.path.join(WORK, 'conformance', 'index.json')
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def match(rec, flt):
    for k, v in flt.items():
        if isinstance(v, list):
            if rec.get(k) not in v:
                return False
        elif rec.get(k) != v:
            return False
    return True


def decoder_inputs(m, idx):
    """The decoder inputs: external streams, Fraunhofer streams, conformance bitstreams (from
    index.json, `idx`). Each has id, path, hash, tags, args (the transport options)."""
    out = []
    targs = m['conformance']['transport_args']
    for e in m['external']:
        if e.get('kind') == 'stream':
            out.append({'id': 'rw-' + safe_name(os.path.basename(e['path'])), 'path': e['path'],
                        'sha256': e['sha256'], 'tags': e['tags'], 'local_only': True,
                        'args': targs[e['transport']]})
    for e in m['fraunhofer']['files']:
        if e['file'].endswith(('.mp4', '.m4a')):
            out.append({'id': 'fhg-' + safe_name(e['file']), 'path': 'fraunhofer/' + e['file'],
                        'sha256': e.get('sha256'),
                        'tags': ['fraunhofer', 'local-only', 'decoder'] + e.get('tags', []),
                        'local_only': True, 'args': targs['mp4']})
    if idx is not None:
        for sel in m['conformance']['selections']:
            for r in idx['files']:
                if not match(r, sel['filter']):
                    continue
                tags = ['conformance', 'decoder', r['set'], r['role'], r['group']] + \
                    sel.get('tags', [])
                if r.get('frame_length_flag') == 1:
                    tags.append('frame-length-flag')
                out.append({'id': f'conf-{"usac-" if r["set"] == "23003-7" else ""}'
                                  f'{safe_name(os.path.basename(r["file"]))}',
                            'path': 'conformance/' + r['file'], 'md5': r['md5'],
                            'channels': r.get('channels'), 'tags': tags,
                            'args': targs[r['container']]})
    return out


def decoder_cases(m, inputs):
    """Decoder entries: each rule of corpus.json decoder_cases applied to the matching inputs
    (by tags, optionally a minimum channel count), once per variant."""
    out = []
    for rule in m['decoder_cases']:
        want = rule['inputs']
        for e in inputs:
            if not all(t in e['tags'] for t in want.get('tags', [])):
                continue
            if 'min_channels' in want and (e.get('channels') or 0) < want['min_channels']:
                continue
            for v in rule['variants']:
                local = e.get('local_only')
                d = {'name': f'{"local-" if local else ""}{rule["id"]}-{v}-{e["id"]}',
                     'kind': 'decode', 'input': e['path'],
                     'args': e['args'] + m['decoder_variants'][v],
                     'tags': ['decoder', rule['id'], v] + e['tags']}
                for k in ('md5', 'sha256'):
                    if e.get(k):
                        d[k] = e[k]
                if local:
                    d['local_only'] = True
                out.append(d)
    return out


def expand(m):
    """The runnable entries ({name, kind, input, args, ...}, the format of scripts/e2e.py)."""
    idx = load_index()
    if idx is None:
        raise SystemExit('work/conformance/index.json is missing: run scripts/fetch_conformance.py '
                         '[--usac] first')
    out = encoder_cases(m) + decoder_cases(m, decoder_inputs(m, idx))
    names = collections.Counter(e['name'] for e in out)
    dup = [n for n, k in names.items() if k > 1]
    if dup:
        raise SystemExit(f'duplicate entry names: {dup[:5]}')
    return out


def input_items(m):
    """Every input file with its pin: external (sha256), Fraunhofer (sha256 or null),
    conformance inputs of the pinned entries (md5), synthetic sets (digest)."""
    out = []
    for e in m['external']:
        out.append({'path': e['path'], 'sha256': e['sha256'], 'local_only': True,
                    'tags': e['tags'] + [e.get('kind', '')]})
    for e in m['fraunhofer']['files']:
        out.append({'path': 'fraunhofer/' + e['file'], 'sha256': e.get('sha256'),
                    'local_only': True, 'tags': ['fraunhofer', 'local-only'] + e.get('tags', [])})
    seen = set()
    for e in m.get('entries', []):
        if e['kind'] == 'decode' and e.get('md5') and e['input'] not in seen:
            seen.add(e['input'])
            out.append({'path': e['input'], 'md5': e['md5'], 'tags': ['conformance']})
    return out


def tag_filter(es, tags):
    if not tags:
        return es
    want = [t for t in tags.split(',') if t]
    return [e for e in es if all(t in e.get('tags', []) or t == e.get('kind') for t in want)]


def write_manifest(m):
    """corpus.json with one line per entry (the entries list is generated)."""
    entries = m.pop('entries', [])
    text = json.dumps(m, indent=1, ensure_ascii=False)
    m['entries'] = entries
    body = ',\n'.join('  ' + json.dumps(e, ensure_ascii=False, separators=(',', ':'))
                      for e in entries)
    text = text[:text.rfind('}')].rstrip() + ',\n "entries": [\n' + body + '\n ]\n}\n'
    tmp = MANIFEST + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, MANIFEST)


def cmd_pin(args, m):
    entries = [{k: v for k, v in e.items() if k not in ('tags', 'factors')} for e in expand(m)]
    m['entries'] = entries
    st = matrix_stats(m)
    c = collections.Counter(e['kind'] + ('/local' if e.get('local_only') else '') for e in entries)
    m['entry_stats'] = {'encoder_matrix': st, 'entries': dict(sorted(c.items())),
                        'total': len(entries)}
    write_manifest(m)
    print(json.dumps(m['entry_stats'], indent=1))
    print('corpus.json updated')


def cmd_list(args, m):
    es = expand(m) if (args.fresh or args.tags) else m.get('entries', [])
    if args.inputs:
        es = input_items(m)
    es = tag_filter(es, args.tags)
